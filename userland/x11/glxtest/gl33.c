/*
 * Checks GL_ARB_draw_buffers_blend (skipped, green, when the context does
 * not name it): two draw buffers of a framebuffer object of their own,
 * cleared red, drawn green with blending on, the first replacing (the
 * shared factors) and the second keeping what it had (its own factors),
 * then the second's own equation taking the larger of each channel
 * (yellow); the factors and equations read back for each buffer, a draw
 * buffer there is not refused, and the shared calls making every buffer
 * alike again.
 */
static void
gl33_draw_buffers_blend(void)
{
	static const GLenum buffers[2] = { GL_COLOR_ATTACHMENT0, GL_COLOR_ATTACHMENT1 };
	static const GLfloat red[4] = { 1.0f, 0.0f, 0.0f, 1.0f };
	const char *extensions;
	const char *found;
	GLuint program;
	GLuint framebuffer;
	GLuint textures[2];
	GLint value;
	GLenum error;
	unsigned first;
	unsigned second;
	unsigned index;
	int passed;

	/* Without the extension, nothing to check. */
	extensions = (const char *)glGetString(GL_EXTENSIONS);
	found = strstr(extensions, "GL_ARB_draw_buffers_blend");
	if (found == NULL) {
		printf("GLXTEST GL33 draw-buffers-blend skipped (no GL_ARB_draw_buffers_blend)\n");
		gl33_outcomes[22] = 1;
		return;
	}

	/* The program. */
	program = gl33_program(gl33_vertex_source, gl33_two_greens_source);
	if (program == 0U) {
		gl33_outcomes[22] = gl33_expect("blendi-linked", 0L, 1L);
		return;
	}

	/* The framebuffer object of two RGBA8 textures, both drawn into. */
	glGenTextures(2, textures);
	glGenFramebuffers(1, &framebuffer);
	glBindFramebuffer(GL_FRAMEBUFFER, framebuffer);
	for (index = 0U; index < 2U; index++) {
		glBindTexture(GL_TEXTURE_2D, textures[index]);
		glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, GL33_SIDE, GL33_SIDE, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
		glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
		glFramebufferTexture2D(GL_FRAMEBUFFER, buffers[index], GL_TEXTURE_2D, textures[index], 0);
	}
	glBindTexture(GL_TEXTURE_2D, 0U);
	glDrawBuffers(2, buffers);

	/* The first replaces (the shared factors), the second keeps what it had (its own). */
	glEnable(GL_BLEND);
	glBlendFunc(GL_ONE, GL_ZERO);
	glBlendFunci(1U, GL_ZERO, GL_ONE);
	(void)glGetError();
	glBlendFunci(4U, GL_ONE, GL_ONE);
	error = glGetError();
	passed = gl33_expect("blendi-buffer-range", (long)error, (long)GL_INVALID_VALUE);
	value = 0;
	glGetIntegeri_v(GL_BLEND_SRC_RGB, 1U, &value);
	passed &= gl33_expect("blendi-second-src", (long)value, (long)GL_ZERO);
	value = 0;
	glGetIntegerv(GL_BLEND_SRC_RGB, &value);
	passed &= gl33_expect("blendi-shared-src", (long)value, (long)GL_ONE);

	/* Both cleared red, then the square drawn green. */
	glClearBufferfv(GL_COLOR, 0, red);
	glClearBufferfv(GL_COLOR, 1, red);
	glUseProgram(program);
	glUniform4f(glGetUniformLocation(program, "u_rect"), 0.0f, 0.0f, 1.0f, 1.0f);
	glBindVertexArray(gl33_square);
	glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
	glReadBuffer(GL_COLOR_ATTACHMENT0);
	first = gl33_read(GL33_SIDE / 2, GL33_SIDE / 2);
	glReadBuffer(GL_COLOR_ATTACHMENT1);
	second = gl33_read(GL33_SIDE / 2, GL33_SIDE / 2);
	printf("GLXTEST GL33 draw-buffers-blend first=%06x second=%06x\n", first, second);
	passed &= gl33_expect("blendi-first", (long)first, (long)GL33_GREEN);
	passed &= gl33_expect("blendi-second", (long)second, (long)GL33_RED);

	/* The second's own equation: the larger of each channel, red and green making yellow. */
	glBlendFunci(1U, GL_ONE, GL_ONE);
	glBlendEquationi(1U, GL_MAX);
	value = 0;
	glGetIntegeri_v(GL_BLEND_EQUATION_RGB, 1U, &value);
	passed &= gl33_expect("blendi-second-equation", (long)value, (long)GL_MAX);
	value = 0;
	glGetIntegerv(GL_BLEND_EQUATION_RGB, &value);
	passed &= gl33_expect("blendi-shared-equation", (long)value, (long)GL_FUNC_ADD);
	glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
	second = gl33_read(GL33_SIDE / 2, GL33_SIDE / 2);
	printf("GLXTEST GL33 draw-buffers-blend max=%06x\n", second);
	passed &= gl33_expect("blendi-max", (long)second, 0xffff00L);

	/* The shared calls make every buffer alike again. */
	glBlendFunc(GL_ONE, GL_ZERO);
	glBlendEquation(GL_FUNC_ADD);
	value = 0;
	glGetIntegeri_v(GL_BLEND_EQUATION_RGB, 1U, &value);
	passed &= gl33_expect("blendi-alike-equation", (long)value, (long)GL_FUNC_ADD);
	value = 0;
	glGetIntegeri_v(GL_BLEND_DST_RGB, 1U, &value);
	passed &= gl33_expect("blendi-alike-dst", (long)value, (long)GL_ZERO);
	glDisable(GL_BLEND);
	error = glGetError();
	passed &= gl33_expect("blendi-glerror", (long)error, (long)GL_NO_ERROR);

	/* What the check made goes. */
	glReadBuffer(GL_COLOR_ATTACHMENT0);
	glBindFramebuffer(GL_FRAMEBUFFER, gl33_framebuffer);
	glDeleteFramebuffers(1, &framebuffer);
	glDeleteTextures(2, textures);
	glUseProgram(0U);
	glDeleteProgram(program);
	gl33_outcomes[22] = passed;
}

