/* Prints one of the start's checks, counting it when the value is not the one expected; returns 1 when it is. */
static int
gl33_expect(
	const char *what,
	long got,
	long expected)
{
	/* A value that differs is a failure. */
	if (got != expected) {
		gl33_failures++;
		printf("GLXTEST GL33 check %s got=%ld expected=%ld FAILED\n", what, got, expected);
		return 0;
	}

	/* Succeeded: the line. */
	printf("GLXTEST GL33 check %s got=%ld expected=%ld ok\n", what, got, expected);
	return 1;
}

/*
 * Makes a program of shaders of their types and GLSL sources, the corners
 * at location 0, capturing the outputs of the names given (interleaved;
 * none when the count is 0); 0 with a line when it does not link.
 */
static GLuint
gl40_program(
	const GLenum *types,
	const char *const *sources,
	unsigned count,
	const char *const *captures,
	GLsizei capture_count)
{
	GLuint program;
	GLuint shaders[5];
	GLint linked;
	unsigned index;
	char log[512];

	/* The stages, attached. */
	program = glCreateProgram();
	for (index = 0U; index < count && index < 5U; index++) {
		shaders[index] = gl33_shader(types[index], sources[index]);
		if (shaders[index] != 0U)
			glAttachShader(program, shaders[index]);
	}

	/* The outputs captured, the corners' location, and the link. */
	if (capture_count != 0)
		glTransformFeedbackVaryings(program, capture_count, captures, GL_INTERLEAVED_ATTRIBS);
	glBindAttribLocation(program, GL33_POSITION, "a_position");
	glLinkProgram(program);
	for (index = 0U; index < count && index < 5U; index++) {
		if (shaders[index] != 0U)
			glDeleteShader(shaders[index]);
	}

	/* Linked. */
	linked = GL_FALSE;
	glGetProgramiv(program, GL_LINK_STATUS, &linked);
	if (!linked) {
		log[0] = '\0';
		glGetProgramInfoLog(program, (GLsizei)sizeof(log), NULL, log);
		printf("GLXTEST GL40 link failed: %s\n", log);
		glDeleteProgram(program);
		return 0U;
	}

	/* Succeeded: the program. */
	return program;
}

/* Makes a vertex array of corners at location 0 (its buffer in *buffer). */
static GLuint
gl40_array(
	const GLfloat *corners,
	GLsizei count,
	GLuint *buffer)
{
	GLuint array;

	/* The array and its buffer of two floats a corner. */
	glGenVertexArrays(1, &array);
	glBindVertexArray(array);
	glGenBuffers(1, buffer);
	glBindBuffer(GL_ARRAY_BUFFER, *buffer);
	glBufferData(GL_ARRAY_BUFFER, (GLsizeiptr)count * 2 * (GLsizeiptr)sizeof(GLfloat), corners, GL_STATIC_DRAW);
	glVertexAttribPointer(GL33_POSITION, 2, GL_FLOAT, GL_FALSE, 0, NULL);
	glEnableVertexAttribArray(GL33_POSITION);
	glBindBuffer(GL_ARRAY_BUFFER, 0U);

	/* Succeeded: the array, bound. */
	return array;
}

/* Makes a buffer for transform feedback of a size, every byte 0xff (a float of it is a NaN no capture writes). */
static GLuint
gl40_feedback_buffer(
	GLsizeiptr size)
{
	unsigned char bytes[1024];
	GLuint buffer;

	/* The bytes (no more than the scene's buffers take). */
	if (size > (GLsizeiptr)sizeof(bytes))
		size = (GLsizeiptr)sizeof(bytes);
	memset(bytes, 0xff, sizeof(bytes));

	/* The buffer. */
	glGenBuffers(1, &buffer);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffer);
	glBufferData(GL_TRANSFORM_FEEDBACK_BUFFER, size, bytes, GL_DYNAMIC_COPY);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, 0U);

	/* Succeeded: the buffer. */
	return buffer;
}

/*
 * Checks a #version 400 program in the OpenGL 4.0 context: a patch
 * tessellated over the red target, its fragments shaded by a subroutine
 * the API chose, from a gather of a green texture and a double uniform;
 * green at the middle and at a corner.
 */
static void
gl40_glsl400(void)
{
	static const GLenum types[4] = { GL_VERTEX_SHADER, GL_TESS_CONTROL_SHADER, GL_TESS_EVALUATION_SHADER, GL_FRAGMENT_SHADER };
	static const char *const sources[4] = { gl40_vertex_source, gl40_control_source, gl40_evaluation_source, gl40_fragment_source };
	static const GLubyte green[16] = { 0, 255, 0, 255, 0, 255, 0, 255, 0, 255, 0, 255, 0, 255, 0, 255 };
	GLuint program;
	GLuint texture;
	GLuint chosen;
	GLint version;
	GLenum error;
	unsigned got;
	int passed;

	/* The program. */
	program = gl40_program(types, sources, 4U, NULL, 0);
	if (program == 0U) {
		gl33_outcomes[27] = gl33_expect("glsl400-linked", 0L, 1L);
		return;
	}

	/* A 2x2 green texture. */
	glGenTextures(1, &texture);
	glActiveTexture(GL_TEXTURE0);
	glBindTexture(GL_TEXTURE_2D, texture);
	glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, 2, 2, 0, GL_RGBA, GL_UNSIGNED_BYTE, green);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);

	/* The uniforms, and the subroutine that checks them chosen. */
	glUseProgram(program);
	glUniform1i(glGetUniformLocation(program, "u_texture"), 0);
	glUniform1d(glGetUniformLocation(program, "u_half"), 0.5);
	chosen = glGetSubroutineIndex(program, GL_FRAGMENT_SHADER, "shade_checked");
	glUniformSubroutinesuiv(GL_FRAGMENT_SHADER, 1, &chosen);

	/* The patch of the square's corners over red. */
	glBindVertexArray(gl33_square);
	glBindFramebuffer(GL_FRAMEBUFFER, gl33_framebuffer);
	gl33_clear(GL33_RED);
	glPatchParameteri(GL_PATCH_VERTICES, 4);
	glDrawArrays(GL_PATCHES, 0, 4);
	glPatchParameteri(GL_PATCH_VERTICES, 3);
	passed = 1;
	got = gl33_read(GL33_SIDE / 2, GL33_SIDE / 2);
	printf("GLXTEST GL40 glsl400 got=%06x\n", got);
	passed &= gl33_expect("glsl400-draw", (long)got, (long)GL33_GREEN);
	got = gl33_read(0, 0);
	passed &= gl33_expect("glsl400-corner", (long)got, (long)GL33_GREEN);

	/* The context's GLSL takes 4.00 (the version GL names in its numbers). */
	version = 0;
	glGetIntegerv(GL_MAJOR_VERSION, &version);
	passed &= gl33_expect("glsl400-major", (long)version, 4L);
	error = glGetError();
	passed &= gl33_expect("glsl400-glerror", (long)error, (long)GL_NO_ERROR);

	/* What the check made goes. */
	glUseProgram(0U);
	glDeleteProgram(program);
	glDeleteTextures(1, &texture);
	glBindVertexArray(0U);
	gl33_outcomes[27] = passed;
}

/*
 * Checks the transform feedback of a geometry shader: two triangles drawn
 * in two instances, two invocations of each emitting a strip of four
 * vertices (two triangles); every vertex is captured in GL's order (the
 * instances, the input primitives, the invocations, each strip's second
 * triangle turned round), and the primitives written and generated are
 * the sixteen triangles.
 */
static void
gl40_geometry_capture(void)
{
	static const GLenum types[3] = { GL_VERTEX_SHADER, GL_GEOMETRY_SHADER, GL_FRAGMENT_SHADER };
	static const char *const sources[3] = { gl40_instance_source, gl40_geometry_source, gl40_green_source };
	static const char *const captures[1] = { "g_mark" };
	static const GLfloat corners[12] = { -1.0f, -1.0f, 1.0f, -1.0f, -1.0f, 1.0f, 1.0f, -1.0f, 1.0f, 1.0f, -1.0f, 1.0f };
	GLuint program;
	GLuint array;
	GLuint corner_buffer;
	GLuint buffer;
	GLuint queries[2];
	GLuint written;
	GLuint generated;
	GLenum error;
	int passed;

	/* The program. */
	program = gl40_program(types, sources, 3U, captures, 1);
	if (program == 0U) {
		gl33_outcomes[28] = gl33_expect("geometry-capture-linked", 0L, 1L);
		return;
	}

	/* The two triangles, captured into a buffer of 64 vertices' room while the queries count. */
	array = gl40_array(corners, 6, &corner_buffer);
	buffer = gl40_feedback_buffer(64 * 16);
	glBindFramebuffer(GL_FRAMEBUFFER, gl33_framebuffer);
	glUseProgram(program);
	glBindBufferBase(GL_TRANSFORM_FEEDBACK_BUFFER, 0U, buffer);
	glGenQueries(2, queries);
	glBeginQuery(GL_TRANSFORM_FEEDBACK_PRIMITIVES_WRITTEN, queries[0]);
	glBeginQuery(GL_PRIMITIVES_GENERATED, queries[1]);
	glBeginTransformFeedback(GL_TRIANGLES);
	glDrawArraysInstanced(GL_TRIANGLES, 0, 6, 2);
	glEndTransformFeedback();
	glEndQuery(GL_PRIMITIVES_GENERATED);
	glEndQuery(GL_TRANSFORM_FEEDBACK_PRIMITIVES_WRITTEN);
	error = glGetError();
	passed = gl33_expect("geometry-capture-glerror", (long)error, (long)GL_NO_ERROR);

	/* The counts. */
	written = 0U;
	glGetQueryObjectuiv(queries[0], GL_QUERY_RESULT, &written);
	generated = 0U;
	glGetQueryObjectuiv(queries[1], GL_QUERY_RESULT, &generated);
	printf("GLXTEST GL40 geometry-capture written=%u generated=%u\n", written, generated);
	passed &= gl33_expect("geometry-capture-written", (long)written, 16L);
	passed &= gl33_expect("geometry-capture-generated", (long)generated, 16L);

	/* The vertices, in order. */
	passed &= gl40_geometry_values(buffer);

	/* What the check made goes. */
	glDeleteQueries(2, queries);
	glBindBufferBase(GL_TRANSFORM_FEEDBACK_BUFFER, 0U, 0U);
	glDeleteBuffers(1, &buffer);
	glDeleteBuffers(1, &corner_buffer);
	glUseProgram(0U);
	glDeleteProgram(program);
	glBindVertexArray(0U);
	glDeleteVertexArrays(1, &array);
	gl33_outcomes[28] = passed;
}

/*
 * Checks the marks the geometry shader's capture wrote: for each
 * instance, triangle and invocation, the strip's vertices 0 1 2 and 2 1
 * 3, and nothing after them.  Returns 1 when they are all as expected.
 */
static int
gl40_geometry_values(
	GLuint buffer)
{
	static const unsigned order[6] = { 0U, 1U, 2U, 2U, 1U, 3U };
	GLfloat marks[65][4];
	GLfloat wanted[4];
	unsigned vertex;
	unsigned differs;
	unsigned bits;
	int passed;
	int other;

	/* The buffer's marks. */
	memset(marks, 0, sizeof(marks));
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffer);
	glGetBufferSubData(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)sizeof(marks[0]) * 64, marks);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, 0U);

	/* Each of the 48 vertices: instance, triangle, invocation, the strip's vertex. */
	differs = 0U;
	for (vertex = 0U; vertex < 48U; vertex++) {
		wanted[0] = (GLfloat)(vertex / 24U);
		wanted[1] = (GLfloat)((vertex / 12U) % 2U);
		wanted[2] = (GLfloat)((vertex / 6U) % 2U);
		wanted[3] = (GLfloat)order[vertex % 6U];
		other = memcmp(marks[vertex], wanted, sizeof(wanted));
		if (other == 0)
			continue;

		/* A vertex that differs, the first one shown. */
		if (differs == 0U) {
			printf("GLXTEST GL40 geometry-capture vertex=%u got=%g,%g,%g,%g\n", vertex, (double)marks[vertex][0],
			       (double)marks[vertex][1], (double)marks[vertex][2], (double)marks[vertex][3]);
		}
		differs++;
	}
	passed = gl33_expect("geometry-capture-order", (long)differs, 0L);

	/* Nothing written after them (the buffer's bytes stay 0xff). */
	memcpy(&bits, &marks[48][0], sizeof(bits));
	passed &= gl33_expect("geometry-capture-end", (long)bits, 0xffffffffL);

	/* Succeeded: whether they were as expected. */
	return passed;
}

/*
 * Checks a geometry shader's capture of vertex streams: four points, for
 * each one vertex on stream 0, two on stream 1 and one on stream 3, into
 * buffers 0, 1 and 3 (gl_NextBuffer); the values of each stream in
 * order, the primitives written and generated on each stream, and
 * glDrawTransformFeedbackStream of stream 1.
 */
static void
gl40_stream_capture(void)
{
	static const GLenum types[3] = { GL_VERTEX_SHADER, GL_GEOMETRY_SHADER, GL_FRAGMENT_SHADER };
	static const char *const sources[3] = { gl40_point_source, gl40_streams_source, gl40_green_source };
	static const char *const captures[6] = { "s_zero", "gl_NextBuffer", "s_one", "gl_NextBuffer", "gl_NextBuffer", "s_three" };
	static const long wanted[4] = { 4L, 8L, 0L, 4L };
	GLuint program;
	GLuint array;
	GLuint feedback;
	GLuint buffers[4];
	GLuint written[4];
	GLuint generated[4];
	GLuint counts;
	GLenum error;
	unsigned stream;
	int passed;

	/* The program. */
	program = gl40_program(types, sources, 3U, captures, 6);
	if (program == 0U) {
		gl33_outcomes[29] = gl33_expect("stream-capture-linked", 0L, 1L);
		return;
	}

	/* A transform feedback object of buffers at binding points 0, 1 and 3 (2 takes nothing). */
	glGenVertexArrays(1, &array);
	glBindVertexArray(array);
	glGenTransformFeedbacks(1, &feedback);
	glBindTransformFeedback(GL_TRANSFORM_FEEDBACK, feedback);
	for (stream = 0U; stream < 4U; stream++) {
		buffers[stream] = gl40_feedback_buffer(256);
		if (stream != 2U)
			glBindBufferBase(GL_TRANSFORM_FEEDBACK_BUFFER, stream, buffers[stream]);
	}

	/* The points captured while each stream's queries count. */
	glGenQueries(4, written);
	glGenQueries(4, generated);
	glBindFramebuffer(GL_FRAMEBUFFER, gl33_framebuffer);
	glUseProgram(program);
	for (stream = 0U; stream < 4U; stream++) {
		glBeginQueryIndexed(GL_TRANSFORM_FEEDBACK_PRIMITIVES_WRITTEN, stream, written[stream]);
		glBeginQueryIndexed(GL_PRIMITIVES_GENERATED, stream, generated[stream]);
	}
	glBeginTransformFeedback(GL_POINTS);
	glDrawArrays(GL_POINTS, 0, 4);
	glEndTransformFeedback();
	for (stream = 0U; stream < 4U; stream++) {
		glEndQueryIndexed(GL_TRANSFORM_FEEDBACK_PRIMITIVES_WRITTEN, stream);
		glEndQueryIndexed(GL_PRIMITIVES_GENERATED, stream);
	}
	error = glGetError();
	passed = gl33_expect("stream-capture-glerror", (long)error, (long)GL_NO_ERROR);

	/* Each stream's counts. */
	for (stream = 0U; stream < 4U; stream++) {
		counts = 99U;
		glGetQueryObjectuiv(written[stream], GL_QUERY_RESULT, &counts);
		printf("GLXTEST GL40 stream-capture stream=%u written=%u\n", stream, counts);
		passed &= gl33_expect("stream-capture-written", (long)counts, wanted[stream]);
		counts = 99U;
		glGetQueryObjectuiv(generated[stream], GL_QUERY_RESULT, &counts);
		printf("GLXTEST GL40 stream-capture stream=%u generated=%u\n", stream, counts);
		passed &= gl33_expect("stream-capture-generated", (long)counts, wanted[stream]);
	}

	/* The values, and stream 1's vertices drawn again. */
	passed &= gl40_stream_values(buffers);
	passed &= gl40_stream_draw(feedback, buffers[1]);

	/* What the check made goes. */
	glDeleteQueries(4, written);
	glDeleteQueries(4, generated);
	glBindTransformFeedback(GL_TRANSFORM_FEEDBACK, 0U);
	glDeleteTransformFeedbacks(1, &feedback);
	glDeleteBuffers(4, buffers);
	glUseProgram(0U);
	glDeleteProgram(program);
	glBindVertexArray(0U);
	glDeleteVertexArrays(1, &array);
	gl33_outcomes[29] = passed;
}

/*
 * Checks the values each stream's buffer took: stream 0 the points'
 * numbers, stream 1 each number with 0 and 1, stream 3 the numbers and
 * 100; nothing in buffer 2.  Returns 1 when they are all as expected.
 */
static int
gl40_stream_values(
	const GLuint *buffers)
{
	GLfloat zero[4];
	GLfloat one[8][2];
	GLfloat three[4];
	GLfloat untouched;
	unsigned bits;
	unsigned point;
	unsigned differs;
	int passed;

	/* The buffers' values. */
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffers[0]);
	glGetBufferSubData(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)sizeof(zero), zero);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffers[1]);
	glGetBufferSubData(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)sizeof(one), one);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffers[2]);
	glGetBufferSubData(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)sizeof(untouched), &untouched);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffers[3]);
	glGetBufferSubData(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)sizeof(three), three);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, 0U);

	/* Each point's values on each stream. */
	differs = 0U;
	for (point = 0U; point < 4U; point++) {
		if (zero[point] != (GLfloat)point)
			differs++;
		if (one[2U * point][0] != (GLfloat)point || one[2U * point][1] != 0.0f)
			differs++;
		if (one[2U * point + 1U][0] != (GLfloat)point || one[2U * point + 1U][1] != 1.0f)
			differs++;
		if (three[point] != (GLfloat)point + 100.0f)
			differs++;
	}
	printf("GLXTEST GL40 stream-capture zero=%g,%g one=%g,%g,%g,%g three=%g,%g\n", (double)zero[0], (double)zero[3],
	       (double)one[0][0], (double)one[0][1], (double)one[1][0], (double)one[1][1], (double)three[0], (double)three[3]);
	passed = gl33_expect("stream-capture-values", (long)differs, 0L);

	/* Buffer 2 as it was. */
	memcpy(&bits, &untouched, sizeof(bits));
	passed &= gl33_expect("stream-capture-untouched", (long)bits, 0xffffffffL);

	/* Succeeded: whether they were as expected. */
	return passed;
}

/*
 * Draws the vertices stream 1 captured (into a buffer) with
 * glDrawTransformFeedbackStream as points while GL_PRIMITIVES_GENERATED
 * counts them: the eight.  Returns 1 when they are counted so.
 */
static int
gl40_stream_draw(
	GLuint feedback,
	GLuint buffer)
{
	static const GLenum types[2] = { GL_VERTEX_SHADER, GL_FRAGMENT_SHADER };
	static const char *const sources[2] = { gl40_stream_draw_source, gl40_green_source };
	GLuint program;
	GLuint array;
	GLuint query;
	GLuint points;
	GLenum error;
	int passed;

	/* The program. */
	program = gl40_program(types, sources, 2U, NULL, 0);
	if (program == 0U)
		return gl33_expect("stream-draw-linked", 0L, 1L);

	/* The vertices from stream 1's buffer. */
	glGenVertexArrays(1, &array);
	glBindVertexArray(array);
	glBindBuffer(GL_ARRAY_BUFFER, buffer);
	glVertexAttribPointer(0U, 2, GL_FLOAT, GL_FALSE, 0, NULL);
	glEnableVertexAttribArray(0U);
	glBindBuffer(GL_ARRAY_BUFFER, 0U);

	/* Drawn while counted. */
	glUseProgram(program);
	glGenQueries(1, &query);
	glBeginQuery(GL_PRIMITIVES_GENERATED, query);
	glDrawTransformFeedbackStream(GL_POINTS, feedback, 1U);
	glEndQuery(GL_PRIMITIVES_GENERATED);
	points = 0U;
	glGetQueryObjectuiv(query, GL_QUERY_RESULT, &points);
	printf("GLXTEST GL40 stream-draw points=%u\n", points);
	passed = gl33_expect("stream-draw-points", (long)points, 8L);
	error = glGetError();
	passed &= gl33_expect("stream-draw-glerror", (long)error, (long)GL_NO_ERROR);

	/* What the check made goes. */
	glDeleteQueries(1, &query);
	glUseProgram(0U);
	glDeleteProgram(program);
	glBindVertexArray(0U);
	glDeleteVertexArrays(1, &array);

	/* Succeeded: whether they were counted. */
	return passed;
}

/*
 * Checks the transform feedback after a tessellation evaluation shader:
 * two quad patches tessellated at level 2, each eight triangles whose
 * coordinates are the grid's (halves) and cover the patch once, the
 * first patch's before the second's; sixteen primitives written.
 */
static void
gl40_tessellation_capture(void)
{
	static const GLenum types[4] = { GL_VERTEX_SHADER, GL_TESS_CONTROL_SHADER, GL_TESS_EVALUATION_SHADER, GL_FRAGMENT_SHADER };
	static const char *const sources[4] = { gl40_vertex_source, gl40_control_source, gl40_evaluation_source, gl40_green_source };
	static const char *const captures[2] = { "t_coord", "t_patch" };
	static const GLfloat corners[16] = {
		-1.0f, -1.0f, 0.0f, -1.0f, -1.0f, 1.0f, 0.0f, 1.0f,
		0.0f, -1.0f, 1.0f, -1.0f, 0.0f, 1.0f, 1.0f, 1.0f
	};
	GLuint program;
	GLuint array;
	GLuint corner_buffer;
	GLuint buffer;
	GLuint query;
	GLuint written;
	GLenum error;
	int passed;

	/* The program. */
	program = gl40_program(types, sources, 4U, captures, 2);
	if (program == 0U) {
		gl33_outcomes[30] = gl33_expect("tessellation-capture-linked", 0L, 1L);
		return;
	}

	/* The two patches, captured as triangles while the query counts. */
	array = gl40_array(corners, 8, &corner_buffer);
	buffer = gl40_feedback_buffer(1024);
	glBindFramebuffer(GL_FRAMEBUFFER, gl33_framebuffer);
	glUseProgram(program);
	glBindBufferBase(GL_TRANSFORM_FEEDBACK_BUFFER, 0U, buffer);
	glGenQueries(1, &query);
	glBeginQuery(GL_TRANSFORM_FEEDBACK_PRIMITIVES_WRITTEN, query);
	glPatchParameteri(GL_PATCH_VERTICES, 4);
	glBeginTransformFeedback(GL_TRIANGLES);
	glDrawArrays(GL_PATCHES, 0, 8);
	glEndTransformFeedback();
	glPatchParameteri(GL_PATCH_VERTICES, 3);
	glEndQuery(GL_TRANSFORM_FEEDBACK_PRIMITIVES_WRITTEN);
	error = glGetError();
	passed = gl33_expect("tessellation-capture-glerror", (long)error, (long)GL_NO_ERROR);
	written = 0U;
	glGetQueryObjectuiv(query, GL_QUERY_RESULT, &written);
	printf("GLXTEST GL40 tessellation-capture written=%u\n", written);
	passed &= gl33_expect("tessellation-capture-written", (long)written, 16L);

	/* The triangles. */
	passed &= gl40_tessellation_values(buffer);

	/* What the check made goes. */
	glDeleteQueries(1, &query);
	glBindBufferBase(GL_TRANSFORM_FEEDBACK_BUFFER, 0U, 0U);
	glDeleteBuffers(1, &buffer);
	glDeleteBuffers(1, &corner_buffer);
	glUseProgram(0U);
	glDeleteProgram(program);
	glBindVertexArray(0U);
	glDeleteVertexArrays(1, &array);
	gl33_outcomes[30] = passed;
}

/*
 * Checks the triangles the tessellation's capture wrote (a coordinate and
 * the patch, three words a vertex): each of the 48 vertices of its patch
 * (the first 24 patch 0's), its coordinates halves, each triangle an
 * eighth of the patch (twice its area a quarter).  Returns 1 when they
 * are all as expected.
 */
static int
gl40_tessellation_values(
	GLuint buffer)
{
	GLfloat words[48][3];
	GLfloat twice;
	GLfloat u[3];
	GLfloat v[3];
	GLint patch;
	unsigned triangle;
	unsigned corner;
	unsigned differs;
	int passed;

	/* The buffer's vertices. */
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, buffer);
	glGetBufferSubData(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)sizeof(words), words);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, 0U);

	/* Each triangle: its patch, its corners on the grid, its area. */
	differs = 0U;
	for (triangle = 0U; triangle < 16U; triangle++) {
		for (corner = 0U; corner < 3U; corner++) {
			u[corner] = words[3U * triangle + corner][0];
			v[corner] = words[3U * triangle + corner][1];
			memcpy(&patch, &words[3U * triangle + corner][2], sizeof(patch));
			if (patch != (GLint)(triangle / 8U))
				differs++;
			if (u[corner] * 2.0f != (GLfloat)(int)(u[corner] * 2.0f) ||
			    v[corner] * 2.0f != (GLfloat)(int)(v[corner] * 2.0f))
				differs++;
		}
		twice = (u[1] - u[0]) * (v[2] - v[0]) - (u[2] - u[0]) * (v[1] - v[0]);
		if (twice < 0.0f)
			twice = -twice;
		if (twice != 0.25f)
			differs++;
	}
	printf("GLXTEST GL40 tessellation-capture first=%g,%g second=%g,%g differs=%u\n", (double)words[0][0], (double)words[0][1],
	       (double)words[1][0], (double)words[1][1], differs);
	passed = gl33_expect("tessellation-capture-triangles", (long)differs, 0L);

	/* Succeeded: whether they were as expected. */
	return passed;
}
