/*
 * glxtest's OpenGL 3.3 scene, in a 3.3 compatibility context made by
 * glXCreateContextAttribsARB (and its OpenGL 4.0 scene, the same in a 4.0
 * one with 4.0's outcomes after 3.3's): the start checks OpenGL 3.3's calls in a
 * framebuffer object of 8x8 texels, and each frame shows one square per
 * outcome, green when it is the expected one and red otherwise, and one
 * square drawn with the fixed function:
 *
 *   the version (GL_VERSION, GLSL 3.30, the extensions), a GL_TIME_ELAPSED
 *   query around a draw, glQueryCounter and glGetInteger64v(GL_TIMESTAMP)
 *   in order, a dual-source blend whose second colour is layout(index =
 *   1), one whose second colour glBindFragDataLocationIndexed gave, a
 *   current attribute value from glVertexAttribP4ui (unsigned) and from
 *   glVertexAttribP3ui (signed), an RGB10_A2UI texture drawn into, and
 *   (when the context names GL_ARB_tessellation_shader; skipped, green,
 *   otherwise) a quad patch tessellated over the target, and a square
 *   drawn by glDrawArraysIndirect (GL_ARB_draw_indirect), the debug
 *   output (GL_KHR_debug: a message inserted, an error, a group, a label,
 *   the log), and the clip control (GL_ARB_clip_control: the upper-left
 *   origin turns the picture over and keeps the front faces, the depth
 *   range from 0 clips what lies below it), the texture gathers
 *   (GL_ARB_texture_gather: the red of a 2x2 texture's four texels), and
 *   the vertex attribute binding (GL_ARB_vertex_attrib_binding: two
 *   attributes of one interleaved binding point, then the colour from a
 *   binding point of stride 0), and (when the context names
 *   GL_ARB_texture_cube_map_array; skipped, green, otherwise) a cube map
 *   array's faces looked up by direction and cube, and (when the context
 *   names GL_ARB_sample_shading; skipped, green, otherwise) the sample
 *   shading (GL_ARB_sample_shading: the state of glMinSampleShading and
 *   GL_SAMPLE_SHADING, each sample of a multisample texture shaded with
 *   its own gl_SampleID and gl_SamplePosition), and the doubles
 *   (GL_ARB_gpu_shader_fp64: double uniforms given by glUniform*d and a
 *   uniform block, compared in the shader to 64 bits, their types,
 *   places and values as GL reports them; without the extension, a
 *   shader that requires it must not compile), and GL_ARB_gpu_shader5's
 *   integer and floating-point built-ins (fields of bits, bit counts and
 *   searches, carries, borrows and products' halves written to out
 *   arguments, fma, frexp, ldexp, the 4x8 packs, int converted to uint)
 *   in a 3.30 shader that enables the extension, computed on uniforms,
 *   and (both skipped, green, when the context does not name
 *   GL_ARB_gpu_shader5) the rest of the extension: its limits, gathers
 *   of a component, of depth comparisons, at four constant and at a
 *   computed offset and of a rectangle, an array of samplers indexed by
 *   a uniform, an input interpolated at the centroid, a sample and an
 *   offset, precise, and a geometry shader of two invocations, and an
 *   array of uniform blocks (each element read a block of its own, "B[i]",
 *   read at constant indices, and with GL_ARB_gpu_shader5 at a computed
 *   one), and dFdy and fwidth along GL's rows both in the framebuffer
 *   object and in the window (framebuffer 0, whose rows Vulkan has turned
 *   over), and the transform feedback of GL_ARB_transform_feedback2 and 3
 *   (interleaved names into two buffers by gl_NextBuffer, a component
 *   left as it was by gl_SkipComponents1, the vertices of a capture that
 *   was paused for a draw drawn again by glDrawTransformFeedback, nothing
 *   by stream 1, and three instances of them captured again, each counted
 *   by the indexed query of stream 0 while stream 1's counts none, and a
 *   triangle of indices captured in their order), and (each skipped,
 *   green, when the context does not name its extension) the blending of
 *   each draw buffer (GL_ARB_draw_buffers_blend: two draw buffers blended
 *   with factors and equations of their own), the level of detail a
 *   lookup would take (GL_ARB_texture_query_lod), subroutines
 *   (GL_ARB_shader_subroutine: what GL reports of them, the one a
 *   subroutine uniform starts at and the one glUniformSubroutinesuiv
 *   chose), a geometry shader's vertex streams (GL_ARB_gpu_shader5: only
 *   stream 0's points drawn, and each stream's counted), and the
 *   primitives generated by draws without a geometry shader
 *   (GL_PRIMITIVES_GENERATED).
 *
 * The OpenGL 4.0 scene checks the version (GL_VERSION 4.0, GLSL 4.00)
 * instead of 3.3's, and adds: a #version 400 program of tessellation
 * shaders, a double uniform, a gather and a subroutine drawn green; the
 * transform feedback of a geometry shader (two invocations of each
 * triangle, each a strip of four vertices, in two instances: every
 * vertex captured in GL's order, the primitives written and generated
 * counted); a geometry shader's capture of vertex streams 0, 1 and 3
 * into buffers of their own (each stream's values in order, its
 * primitives written and generated counted, stream 1's vertices drawn by
 * glDrawTransformFeedbackStream); and the transform feedback after a
 * tessellation evaluation shader (two quad patches, each eight triangles
 * of a coordinate grid, the first patch's before the second's).
 *
 * The start's checks each print a line; a check whose value is not the
 * expected one fails the run.
 */

