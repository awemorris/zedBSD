/*
 * Captures a triangle of indices (3, 0, 2 of the square's corners) while
 * transform feedback is active, as desktop GL allows: the vertices'
 * numbers (gl_VertexID) are written in the order the indices give.
 * Returns 1 when every check passes.
 */
static int
gl33_feedback2_indexed(void)
{
	static const char *const names[1] = { "v_mark" };
	static const GLuint indices[3] = { 3U, 0U, 2U };
	const GLfloat *words;
	GLuint program;
	GLuint array;
	GLuint corner_buffer;
	GLuint element_buffer;
	GLuint capture_buffer;
	GLint linked;
	unsigned vertex;
	unsigned differs;
	int passed;

	/* The capture's program, of the vertices' numbers only. */
	program = gl33_program(gl33_capture_source, gl33_plain_source);
	if (program == 0U)
		return gl33_expect("feedback2-indexed-linked", 0L, 1L);
	linked = gl33_relink(program, 1, names, GL_INTERLEAVED_ATTRIBS);
	passed = gl33_expect("feedback2-indexed-linked", (long)linked, 1L);

	/* The square's corners and the indices, and the buffer the numbers go into. */
	glGenVertexArrays(1, &array);
	glBindVertexArray(array);
	glGenBuffers(1, &corner_buffer);
	glBindBuffer(GL_ARRAY_BUFFER, corner_buffer);
	glBufferData(GL_ARRAY_BUFFER, (GLsizeiptr)(8U * sizeof(GLfloat)), NULL, GL_STATIC_DRAW);
	glVertexAttribPointer(GL33_POSITION, 2, GL_FLOAT, GL_FALSE, 0, NULL);
	glEnableVertexAttribArray(GL33_POSITION);
	glBindBuffer(GL_ARRAY_BUFFER, 0U);
	glGenBuffers(1, &element_buffer);
	glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, element_buffer);
	glBufferData(GL_ELEMENT_ARRAY_BUFFER, (GLsizeiptr)sizeof(indices), indices, GL_STATIC_DRAW);
	glGenBuffers(1, &capture_buffer);
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, capture_buffer);
	glBufferData(GL_TRANSFORM_FEEDBACK_BUFFER, (GLsizeiptr)(3U * sizeof(GLfloat)), NULL, GL_STATIC_READ);
	glBindBufferBase(GL_TRANSFORM_FEEDBACK_BUFFER, 0U, capture_buffer);

	/* The triangle of indices, captured. */
	glEnable(GL_RASTERIZER_DISCARD);
	glUseProgram(program);
	glBeginTransformFeedback(GL_TRIANGLES);
	glDrawElements(GL_TRIANGLES, 3, GL_UNSIGNED_INT, NULL);
	glEndTransformFeedback();
	glDisable(GL_RASTERIZER_DISCARD);

	/* The numbers in the indices' order. */
	differs = 0U;
	words = glMapBufferRange(GL_TRANSFORM_FEEDBACK_BUFFER, 0, (GLsizeiptr)(3U * sizeof(GLfloat)), GL_MAP_READ_BIT);
	if (words == NULL)
		differs = 99U;
	for (vertex = 0U; words != NULL && vertex < 3U; vertex++) {
		if (words[vertex] != (GLfloat)indices[vertex])
			differs++;
	}
	if (words != NULL)
		(void)glUnmapBuffer(GL_TRANSFORM_FEEDBACK_BUFFER);
	printf("GLXTEST GL33 transform-feedback2 indexed differs=%u\n", differs);
	passed &= gl33_expect("feedback2-indexed", (long)differs, 0L);

	/* What the check made goes. */
	glBindBuffer(GL_TRANSFORM_FEEDBACK_BUFFER, 0U);
	glBindVertexArray(0U);
	glDeleteVertexArrays(1, &array);
	glDeleteBuffers(1, &corner_buffer);
	glDeleteBuffers(1, &element_buffer);
	glDeleteBuffers(1, &capture_buffer);
	glUseProgram(0U);
	glDeleteProgram(program);

	/* Succeeded: whether the checks passed. */
	return passed;
}

