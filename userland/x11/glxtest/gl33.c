/* Reports whether a fragment shader that requires GL_ARB_gpu_shader_fp64 fails to compile (a context without it). */
static int
gl33_fp64_refused(void)
{
	const char *source;
	GLuint shader;
	GLint compiled;

	/* The doubles' shader. */
	source = gl33_fp64_source;
	shader = glCreateShader(GL_FRAGMENT_SHADER);
	glShaderSource(shader, 1, &source, NULL);
	glCompileShader(shader);
	compiled = GL_TRUE;
	glGetShaderiv(shader, GL_COMPILE_STATUS, &compiled);
	glDeleteShader(shader);

	/* Refused when it did not compile. */
	if (compiled == GL_FALSE)
		return 1;

	/* It compiled. */
	return 0;
}

/*
 * Fills a uniform buffer for the program's block of doubles at the places
 * GL reports of its members (which must be std140's: 0, 32 and 64, the
 * matrix's columns 16 bytes apart, 96 bytes in all) and binds it to the
 * block.  Returns 1 when the places are std140's, 0 otherwise.
 */
static int
gl33_fp64_block(
	GLuint program,
	GLuint *buffer)
{
	static const GLchar *const names[3] = { "b_fine", "b_vec", "b_mat" };
	static const GLdouble vector[3] = { 0.1, -2.5, 1099511627777.0 };
	static const GLdouble matrix[4] = { -2.5, 0.25, 0.1, 1099511627777.0 };
	unsigned char data[256];
	GLuint indices[3];
	GLint offsets[3];
	GLint strides[3];
	GLint size;
	GLuint block;
	GLdouble fine;
	unsigned column;
	int passed;

	/* The block, its size, and its members' offsets and matrix strides. */
	block = glGetUniformBlockIndex(program, "Precise");
	size = 0;
	if (block != GL_INVALID_INDEX)
		glGetActiveUniformBlockiv(program, block, GL_UNIFORM_BLOCK_DATA_SIZE, &size);
	glGetUniformIndices(program, 3, names, indices);
	memset(offsets, 0, sizeof(offsets));
	memset(strides, 0, sizeof(strides));
	glGetActiveUniformsiv(program, 3, indices, GL_UNIFORM_OFFSET, offsets);
	glGetActiveUniformsiv(program, 3, indices, GL_UNIFORM_MATRIX_STRIDE, strides);
	passed = gl33_expect("fp64-block-size", (long)size, 96L);
	passed &= gl33_expect("fp64-offset-vec", (long)offsets[1], 32L);
	passed &= gl33_expect("fp64-offset-mat", (long)offsets[2], 64L);
	passed &= gl33_expect("fp64-matrix-stride", (long)strides[2], 16L);
	if (!passed || block == GL_INVALID_INDEX)
		return 0;

	/* The members at their places: 1 + 2^-40, the vector, the matrix by columns. */
	memset(data, 0, sizeof(data));
	fine = 1.0 + 1.0 / 1099511627776.0;
	memcpy(data + offsets[0], &fine, sizeof(fine));
	memcpy(data + offsets[1], vector, sizeof(vector));
	for (column = 0U; column < 2U; column++)
		memcpy(data + offsets[2] + (GLint)column * strides[2], &matrix[column * 2U], 2U * sizeof(GLdouble));

	/* The buffer at binding point 2, read by the block. */
	glGenBuffers(1, buffer);
	glBindBuffer(GL_UNIFORM_BUFFER, *buffer);
	glBufferData(GL_UNIFORM_BUFFER, (GLsizeiptr)size, data, GL_STATIC_DRAW);
	glBindBufferBase(GL_UNIFORM_BUFFER, 2U, *buffer);
	glUniformBlockBinding(program, block, 2U);

	/* Succeeded: the places were std140's. */
	return 1;
}

