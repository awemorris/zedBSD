#!/usr/bin/env python3
"""ws031-p024 increment 3: writes the spill shaders of the host compile test (plan/ws031/tests/i915-vk-compile-test.c,
test_p024_spill_mix) and compiles them with glslc.  Each keeps N values of the pixel live over a loop whose trip
count differs from channel to channel; the loop samples a texture (its reply lands while the values are spilled),
a discard follows while they are still live, and the end sums the products t[k] * t[(7k + 5) % N].  The C test
computes the same in the same order."""
