#!/usr/bin/env python3
# Extracts the constant tables of RFC 6386 from its text (build/sources/specs/webp/rfc6386.txt) into a C include of
# flat arrays, for test-vp8_tables.c to compare vp8-tables.c's values with: an independent path from the same
# specification (the tables are read by name from the RFC's code blocks, page breaks and comments dropped, enum names
# turned into their values).  Run with python3 -I.
#   python3 -I plan/ws344/tests/vp8-tables-extract.py RFC6386.txt OUT.h
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
import re
import sys

# The tables: C name in the output, the RFC's declaration (a regular expression), the expected count.
TABLES = [
    ("rfc_kf_ymode_tree", r"const tree_index kf_ymode_tree \[2 \* \(num_ymodes - 1\)\] =", 8, 1),
    ("rfc_uv_mode_tree", r"const tree_index uv_mode_tree \[2 \* \(num_uv_modes - 1\)\] =", 6, 1),
    ("rfc_bmode_tree", r"const tree_index bmode_tree \[2 \* \(num_intra_bmodes - 1\)\] =", 18, 1),
    ("rfc_mb_segment_tree", r"const tree_index mb_segment_tree \[2 \* \(4-1\)\] =", 6, 1),
    ("rfc_coeff_tree", r"const tree_index coeff_tree \[2 \* \(num_dct_tokens - 1\)\] =", 22, 1),
    ("rfc_kf_ymode_prob", r"const Prob kf_ymode_prob \[num_ymodes - 1\] =", 4, 1),
    ("rfc_kf_uv_mode_prob", r"const Prob kf_uv_mode_prob \[num_uv_modes - 1\] =", 3, 1),
    ("rfc_kf_bmode_prob", r"const Prob kf_bmode_prob \[num_intra_bmodes\] \[num_intra_bmodes\]\s*\n\s*\[num_intra_bmodes-1\] =", 900, 1),
    ("rfc_coeff_update_probs", r"const Prob coeff_update_probs \[4\] \[8\] \[3\] \[num_dct_tokens-1\] =", 1056, 1),
    ("rfc_default_coeff_probs", r"const Prob default_coeff_probs \[4\] \[8\] \[3\] \[num_dct_tokens - 1\] =", 1056, 1),
    ("rfc_coeff_bands", r"const int coeff_bands \[16\] = \{", 16, 1),
    ("rfc_zigzag", r"static const unsigned int zigzag\[16\] =", 16, 1),
    ("rfc_dc_qlookup", r"static const int dc_qlookup\[QINDEX_RANGE\] =", 128, 1),
    ("rfc_ac_qlookup", r"static const int ac_qlookup\[QINDEX_RANGE\] =", 128, 1),
    ("rfc_pcat1", r"const Prob Pcat1\[\] =", 2, 1),
    ("rfc_pcat2", r"const Prob Pcat2\[\] =", 3, 1),
    ("rfc_pcat3", r"const Prob Pcat3\[\] =", 4, 1),
    ("rfc_pcat4", r"const Prob Pcat4\[\] =", 5, 1),
    ("rfc_pcat5", r"const Prob Pcat5\[\] =", 6, 1),
    ("rfc_pcat6", r"const Prob Pcat6\[\] =", 12, 1),
]

# The enum values the trees name (RFC 6386 8.1, 9.3, 11.2, 13.2).
ENUMS = {
    "DC_PRED": 0, "V_PRED": 1, "H_PRED": 2, "TM_PRED": 3, "B_PRED": 4,
    "B_DC_PRED": 0, "B_TM_PRED": 1, "B_VE_PRED": 2, "B_HE_PRED": 3, "B_LD_PRED": 4, "B_RD_PRED": 5,
    "B_VR_PRED": 6, "B_VL_PRED": 7, "B_HD_PRED": 8, "B_HU_PRED": 9,
    "DCT_0": 0, "DCT_1": 1, "DCT_2": 2, "DCT_3": 3, "DCT_4": 4, "dct_cat1": 5, "dct_cat2": 6, "dct_cat3": 7,
    "dct_cat4": 8, "dct_cat5": 9, "dct_cat6": 10, "dct_eob": 11,
}


def clean(text):
    lines = []
    for line in text.split("\n"):
        if "Bankoski, et al." in line or line.startswith("RFC 6386 ") or line.startswith("\f"):
            continue
        lines.append(line)
    text = "\n".join(lines)
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def extract(text, pattern):
    match = re.search(pattern, text)
    if match is None:
        raise SystemExit("vp8-tables-extract: table not found: " + pattern)
    start = text.index("{", match.start())
    depth = 0
    for position in range(start, len(text)):
        if text[position] == "{":
            depth += 1
        elif text[position] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:position]
    raise SystemExit("vp8-tables-extract: unterminated table: " + pattern)


def values(body):
    out = []
    for sign, token in re.findall(r"(-?)\s*([A-Za-z_][A-Za-z_0-9]*|\d+)", body):
        if token.isdigit():
            value = int(token)
        elif token in ENUMS:
            value = ENUMS[token]
        else:
            raise SystemExit("vp8-tables-extract: unknown name " + token)
        out.append(-value if sign else value)
    return out


def main():
    text = clean(open(sys.argv[1], encoding="utf-8", errors="replace").read())
    out = ["/* Generated by plan/ws344/tests/vp8-tables-extract.py from RFC 6386's text; do not edit. */", ""]
    for name, pattern, count, _ in TABLES:
        found = values(extract(text, pattern))
        if len(found) != count:
            raise SystemExit("vp8-tables-extract: %s has %d values, not %d" % (name, len(found), count))
        out.append("static const int %s[%d] = {" % (name, count))
        for index in range(0, count, 16):
            out.append("\t" + ", ".join(str(v) for v in found[index:index + 16]) + ",")
        out.append("};")
        out.append("")
    open(sys.argv[2], "w").write("\n".join(out))
    print("vp8-tables-extract: %d tables" % len(TABLES))


main()
