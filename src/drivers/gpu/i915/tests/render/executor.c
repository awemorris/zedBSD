/*
 * Starts the executor scenario.
 *
 * Returns at once: the scenario's thread runs the steps after the node is
 * published and logs their verdicts itself.
 */
void
drv_i915_test_render_executor(
	struct i915_device *device)
{
	struct thread *thread;
	int error;

	/* Starts the thread that waits for the node and runs the steps. */
	error = kthread_create(i915_vkx_thread, device, SCHED_PRIORITY_DEFAULT, &thread);
	if (error != 0) {
		kern_logf("i915: vkx: verdict FAIL (the scenario thread cannot be created: %d)\n", error);
		return;
	}

	/* The thread reclaims itself when the steps are done. */
	thread->detached = 1U;
	thread_start(thread);
	kern_logf("i915: vkx: the steps run once the node is published\n");
}

/* Runs the scenario: waits for the node, sets up, runs every step, tears down and logs the verdict. */
static void
i915_vkx_thread(
	void *argument)
{
	struct i915_device *device;
	struct i915_vkx *x;
	int error;

	/* Waits until the node is published and its worker serves. */
	device = argument;
	error = i915_vkx_wait_node(device);
	if (error != 0) {
		kern_logf("i915: vkx: verdict FAIL (the node was not published within %u s)\n", I915_VKX_WAIT_S);
		return;
	}

	/* Opens the session and makes every object the steps use. */
	x = &i915_vkx_state;
	kern_memset(x, 0, sizeof(*x));
	x->device = device;
	error = i915_vkx_setup(x);
	if (error != 0) {
		kern_logf("i915: vkx: verdict FAIL (setup: %d)\n", error);
		i915_vkx_teardown(x);
		return;
	}

	/* Runs every step; each logs its own verdict. */
	i915_vkx_step_index16(x);
	i915_vkx_step_index32(x);
	i915_vkx_step_viewport(x);
	i915_vkx_step_copy(x);
	i915_vkx_step_grid(x);
	i915_vkx_step_mip_nearest(x);
	i915_vkx_step_mip_linear(x);
	i915_vkx_step_mip_blit(x);

	/* Gives everything back and says how the steps went. */
	i915_vkx_teardown(x);
	if (x->failed != 0U) {
		kern_logf("i915: vkx: verdict FAIL (%u of %u steps passed)\n", x->passed, x->passed + x->failed);
		return;
	}

	kern_logf("i915: vkx: verdict PASS (%u of %u steps passed)\n", x->passed, x->passed + x->failed);
}

/* Waits until the node is published, sleeping a twentieth of a second at a time; ETIMEDOUT when it never is. */
static int
i915_vkx_wait_node(
	struct i915_device *device)
{
	struct i915_completion nap;
	unsigned waited;

	/* A completion nobody signals: each wait on it simply lasts until its deadline. */
	drv_i915_completion_init(&nap, "i915 vkx");

	/* Looks for the published node until the budget is spent. */
	for (waited = 0U; waited < I915_VKX_WAIT_S * 20U; waited++) {
		/* The node is published once the GPU core holds it. */
		if (device->gpu != NULL && device->vk != NULL)
			return 0;

		(void)drv_i915_wait_for_completion(&nap, sched_ticks() + KERN_CLOCK_HZ / 20U);
	}

	/* The node never came. */
	return ETIMEDOUT;
}

/* Opens the session, makes the storage, the objects and the pipelines, and a command pool. */
static int
i915_vkx_setup(
	struct i915_vkx *x)
{
	void *private_session;
	int error;

	/* Opens a session of the node as a client's open would. */
	error = x->device->gpu_ops.open(x->device, &private_session);
	if (error != 0)
		return error;

	x->session = private_session;
	x->render = x->session->vk;
	if (x->render == NULL)
		return ENODEV;

	/* Makes the storage, bound into the session's address space. */
	error = i915_vkx_storage_create(x);
	if (error != 0)
		return error;

	/* Describes the objects over the storage and publishes them. */
	i915_vkx_objects_init(x);
	error = i915_vkx_objects_publish(x);
	if (error != 0)
		return error;

	/* Compiles the four pipelines. */
	error = i915_vkx_pipelines_prepare(x);
	if (error != 0)
		return error;

	/* Writes the vertices and the indices every draw step reads. */
	i915_vkx_vertices_write(x);
	i915_vkx_indices_write(x);

	/* Creates the command pool and its one command buffer through the wire. */
	error = i915_vkx_pool_create(x);
	if (error != 0)
		return error;

	/* Succeeded: every step can record and submit. */
	return 0;
}

/* Gives back everything the setup made, whatever it got to. */
static void
i915_vkx_teardown(
	struct i915_vkx *x)
{
	struct i915_device *device;
	int error;

	/* Destroys the command pool and its buffer through the wire. */
	if (x->pooled != 0) {
		x->used = 0U;
		x->overflow = 0;
		i915_vkx_put32(x, I915_VKX_OP_DESTROY_COMMAND_POOL);
		i915_vkx_put32(x, 1U);
		i915_vkx_put64(x, 0U);
		i915_vkx_put64(x, I915_VKX_ID_POOL);
		i915_vkx_put64(x, 0U);
		error = i915_vkx_execute(x, "destroy the command pool");
		if (error != 0)
			kern_logf("i915: vkx: the command pool was not destroyed: %d\n", error);
		x->pooled = 0;
	}

	/* Withdraws the published objects and releases the kernels. */
	if (x->published != 0)
		i915_vkx_objects_withdraw(x);
	drv_i915_gfx_pipeline_release(&x->color_pipeline);
	drv_i915_gfx_pipeline_release(&x->dynamic_pipeline);
	drv_i915_gfx_pipeline_release(&x->push_pipeline);
	drv_i915_gfx_pipeline_release(&x->tex_pipeline);

	/* Unbinds and destroys the storage. */
	device = x->device;
	if (x->storage != NULL) {
		mutex_lock(&device->mutex);

		drv_i915_gem_unbind_vm(x->storage);
		drv_i915_gem_destroy(&device->gem, x->storage);

		mutex_unlock(&device->mutex);

		x->storage = NULL;
	}

	/* Closes the session, which releases the executor's draw state with it. */
	if (x->session != NULL) {
		device->gpu_ops.close(device, x->session);
		x->session = NULL;
		x->render = NULL;
	}
}

/* Makes the storage object, bound into the session's address space. */
static int
i915_vkx_storage_create(
	struct i915_vkx *x)
{
	struct i915_device *device;
	int error;

	/* Creates the object and binds it, destroying it again when the binding fails. */
	device = x->device;
	mutex_lock(&device->mutex);

	error = drv_i915_gem_create(&device->gem, I915_VKX_STORAGE_BYTES, &x->storage);
	if (error == 0) {
		error = drv_i915_gem_bind_vm(x->session->vm, x->storage);
		if (error != 0) {
			drv_i915_gem_destroy(&device->gem, x->storage);
			x->storage = NULL;
		}
	} else {
		x->storage = NULL;
	}

	mutex_unlock(&device->mutex);

	/* Reports why the storage could not be made. */
	if (error != 0)
		return error;

	/* The steps write and read the storage through its CPU view. */
	x->cpu = x->storage->address;

	/* Succeeded: the storage is bound. */
	return 0;
}

/* Describes the memory, the target, the pass, the framebuffer and the buffers over the storage. */
static void
i915_vkx_objects_init(
	struct i915_vkx *x)
{
	/* The memory is the whole storage. */
	x->memory.vk = x->device->vk;
	x->memory.identity = I915_VKX_IDENTITY;
	x->memory.size = I915_VKX_STORAGE_BYTES;
	x->memory.object = x->storage;

	/* The target: a linear 64x64 RGBA8 image. */
	x->target.format = VK_FORMAT_R8G8B8A8_UNORM;
	x->target.width = I915_VKX_SIZE;
	x->target.height = I915_VKX_SIZE;
	x->target.usage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT;
	x->target.pitch = I915_VKX_SIZE * 4U;
	x->target.bytes = I915_VKX_SIZE * I915_VKX_SIZE * 4U;
	x->target.levels = 1U;
	x->target.memory = &x->memory;
	x->target.offset = I915_VKX_TARGET_OFFSET;
	x->view.image = &x->target;
	x->view.format = VK_FORMAT_R8G8B8A8_UNORM;
	x->view.level_count = 1U;

	/* One subpass writing the one colour attachment, cleared at the begin. */
	x->pass.attachment_count = 1U;
	x->pass.attachments[0].format = VK_FORMAT_R8G8B8A8_UNORM;
	x->pass.attachments[0].load_op = VK_ATTACHMENT_LOAD_OP_CLEAR;
	x->pass.color_attachment = 0U;
	x->pass.depth_attachment = VK_ATTACHMENT_UNUSED;
	x->framebuffer.width = I915_VKX_SIZE;
	x->framebuffer.height = I915_VKX_SIZE;
	x->framebuffer.view_count = 1U;
	x->framebuffer.views[0] = &x->view;

	/* The vertex buffer. */
	x->vertices.size = I915_VKX_VERTEX_BYTES;
	x->vertices.usage = VK_BUFFER_USAGE_VERTEX_BUFFER_BIT;
	x->vertices.memory = &x->memory;
	x->vertices.offset = I915_VKX_VERTEX_OFFSET;

	/* The index buffer. */
	x->indices.size = I915_VKX_INDEX_BYTES;
	x->indices.usage = VK_BUFFER_USAGE_INDEX_BUFFER_BIT;
	x->indices.memory = &x->memory;
	x->indices.offset = I915_VKX_INDEX_OFFSET;

	/* The source and the destination of the copies. */
	x->source.size = I915_VKX_COPY_BYTES;
	x->source.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;
	x->source.memory = &x->memory;
	x->source.offset = I915_VKX_SOURCE_OFFSET;
	x->destination.size = I915_VKX_COPY_BYTES;
	x->destination.usage = VK_BUFFER_USAGE_TRANSFER_DST_BIT;
	x->destination.memory = &x->memory;
	x->destination.offset = I915_VKX_DESTINATION_OFFSET;

	/* The shader modules borrow the generated words, which the compiler only reads. */
	x->place.words = (uint32_t *)(uintptr_t)i915_vkx_place_vert;
	x->place.word_count = sizeof(i915_vkx_place_vert) / 4U;
	x->color.words = (uint32_t *)(uintptr_t)i915_vkx_color_frag;
	x->color.word_count = sizeof(i915_vkx_color_frag) / 4U;
	x->push.words = (uint32_t *)(uintptr_t)i915_vkx_push_frag;
	x->push.word_count = sizeof(i915_vkx_push_frag) / 4U;

	/* The colour pipeline, the one with dynamic viewport and scissor, and the pushed-colour one. */
	i915_vkx_pipeline_init(x, &x->color_pipeline, &x->color, 0);
	i915_vkx_pipeline_init(x, &x->dynamic_pipeline, &x->color, 1);
	i915_vkx_pipeline_init(x, &x->push_pipeline, &x->push, 0);

	/* The mip steps' images, views, samplers, sets and pipeline. */
	i915_vkx_mip_objects_init(x);
}

/* Publishes the objects the wire names under the scenario's identities. */
static int
i915_vkx_objects_publish(
	struct i915_vkx *x)
{
	struct i915_render_session *session;
	int error;

	/* Publishes the buffers, the pass, the framebuffer and the pipelines, stopping at the first refusal. */
	session = x->render;
	error = drv_i915_object_insert(session, I915_VK_OBJ_BUFFER, I915_VKX_ID_VERTICES, &x->vertices);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_BUFFER, I915_VKX_ID_INDICES, &x->indices);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_BUFFER, I915_VKX_ID_SOURCE, &x->source);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_BUFFER, I915_VKX_ID_DESTINATION, &x->destination);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_RENDER_PASS, I915_VKX_ID_PASS, &x->pass);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_FRAMEBUFFER, I915_VKX_ID_FRAMEBUFFER, &x->framebuffer);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_PIPELINE, I915_VKX_ID_COLOR_PIPELINE, &x->color_pipeline);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_PIPELINE, I915_VKX_ID_DYNAMIC_PIPELINE, &x->dynamic_pipeline);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_PIPELINE, I915_VKX_ID_PUSH_PIPELINE, &x->push_pipeline);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_IMAGE, I915_VKX_ID_TEXTURE, &x->texture);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_IMAGE, I915_VKX_ID_CHAIN, &x->chain);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_PIPELINE, I915_VKX_ID_TEX_PIPELINE, &x->tex_pipeline);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_NEAREST, &x->nearest_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_FORCED, &x->forced_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_BIAS, &x->bias_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_LATER, &x->later_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_LINEAR, &x->linear_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_LOD5, &x->lod5_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_LOD5_HALF, &x->lod5_half_set);
	if (error == 0)
		error = drv_i915_object_insert(session, I915_VK_OBJ_DESCRIPTOR_SET, I915_VKX_ID_SET_LOD6, &x->lod6_set);

	/* The teardown withdraws whatever was published, all of it or part of it. */
	x->published = 1;

	/* Reports why an object could not be published. */
	if (error != 0)
		return error;

	/* Succeeded: the wire can name every object. */
	return 0;
}

