/* Appends vkCmdPushConstants of the whole 128-byte block to both stages. */
static void
i915_vkx_push(
	struct i915_vkx *x,
	const uint32_t *block)
{
	unsigned index;

	/* [layout][stages][offset][size][size]{bytes}. */
	i915_vkx_record(x, I915_VKX_OP_PUSH_CONSTANTS);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, I915_VKX_PUSH_BYTES);
	i915_vkx_put64(x, I915_VKX_PUSH_BYTES);
	for (index = 0U; index < I915_VKX_PUSH_BYTES / 4U; index++)
		i915_vkx_put32(x, block[index]);
}

/*
 * Appends the end and a submission of the command buffer, executes the
 * stream and checks the three replies: [90][result][91][result][18][result].
 */
static int
i915_vkx_finish(
	struct i915_vkx *x,
	const char *what)
{
	uint32_t begun;
	uint32_t ended;
	uint32_t submitted;
	int error;

	/* vkEndCommandBuffer: [91][reply][buffer]. */
	i915_vkx_put32(x, I915_VKX_OP_END_COMMAND_BUFFER);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, I915_VKX_ID_COMMAND_BUFFER);

	/* vkQueueSubmit of the one buffer, with no semaphores and no fence. */
	i915_vkx_put32(x, I915_VKX_OP_QUEUE_SUBMIT);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put32(x, 4U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put64(x, I915_VKX_ID_COMMAND_BUFFER);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, 0U);

	/* Runs the stream: the recording, then the submission to its end. */
	error = i915_vkx_execute(x, what);
	if (error != 0)
		return error;

	/* Takes the results of the begin, the end and the submission. */
	begun = i915_vkx_reply32(x, 4U);
	ended = i915_vkx_reply32(x, 12U);
	submitted = i915_vkx_reply32(x, 20U);

	/* Refuses a begin, an end or a submission that did not succeed. */
	if (begun != VK_SUCCESS ||
	    ended != VK_SUCCESS ||
	    submitted != VK_SUCCESS) {
		kern_logf("i915: vkx: %s: begin %d, end %d, submit %d\n",
			  what,
			  (int)begun,
			  (int)ended,
			  (int)submitted);
		return EIO;
	}

	/* Succeeded: the command buffer ran to its end. */
	return 0;
}

/* Expects the whole target in the clear colour, opaque black. */
static void
i915_vkx_expect_clear(
	struct i915_vkx *x)
{
	unsigned index;

	/* Every pixel is the clear colour. */
	for (index = 0U; index < I915_VKX_SIZE * I915_VKX_SIZE; index++)
		x->expected[index] = I915_VKX_BLACK;
}

/* Expects the pixels of columns left .. right - 1 and rows top .. bottom - 1 to hold a pixel value. */
static void
i915_vkx_expect_rect(
	struct i915_vkx *x,
	unsigned left,
	unsigned top,
	unsigned right,
	unsigned bottom,
	uint32_t pixel)
{
	unsigned column;
	unsigned row;

	/* Paints the rectangle into the expected image. */
	for (row = top; row < bottom; row++) {
		for (column = left; column < right; column++)
			x->expected[row * I915_VKX_SIZE + column] = pixel;
	}
}

/* Compares the target with the expected image; EIO when any pixel differs, with the first logged. */
static int
i915_vkx_compare_target(
	struct i915_vkx *x,
	const char *what)
{
	const uint32_t *pixels;
	unsigned differ;
	unsigned first;
	unsigned index;

	/* Reads the target through the CPU view, past any line the CPU still caches. */
	pixels = (const uint32_t *)(const void *)(x->cpu + I915_VKX_TARGET_OFFSET);
	drv_i915_gt_clflush(pixels, I915_VKX_SIZE * I915_VKX_SIZE * 4U);

	/* Counts the pixels that differ and notes the first. */
	differ = 0U;
	first = 0U;
	for (index = 0U; index < I915_VKX_SIZE * I915_VKX_SIZE; index++) {
		if (pixels[index] != x->expected[index]) {
			if (differ == 0U)
				first = index;
			differ++;
		}
	}

	/* Says where the image differs. */
	if (differ != 0U) {
		kern_logf("i915: vkx: %s: %u of %u pixels differ; first at (%u,%u): 0x%08x, expected 0x%08x\n",
			  what,
			  differ,
			  I915_VKX_SIZE * I915_VKX_SIZE,
			  first % I915_VKX_SIZE,
			  first / I915_VKX_SIZE,
			  pixels[first],
			  x->expected[first]);
		return EIO;
	}

	/* Succeeded: the target is exactly the expected image. */
	return 0;
}

/* Logs a step's verdict and counts it. */
static void
i915_vkx_verdict(
	struct i915_vkx *x,
	const char *what,
	int error)
{
	/* A step fails with the error that stopped it. */
	if (error != 0) {
		x->failed++;
		kern_logf("i915: vkx: VKX-%s FAIL (%d)\n", what, error);
		return;
	}

	x->passed++;
	kern_logf("i915: vkx: VKX-%s PASS\n", what);
}

/*
 * INDEX16: one indexed draw of twelve 16-bit indices, bound at byte 4, from
 * index 2, with vertex offset 4, draws the red and the green squares.  A
 * bind offset, first index or vertex offset that were ignored would draw
 * the junk indices or the blue quad that covers the target.
 */
static void
i915_vkx_step_index16(
	struct i915_vkx *x)
{
	int error;

	/* Records the pass, the colour pipeline, the buffers and the draw. */
	i915_vkx_begin(x);
	i915_vkx_begin_pass(x);
	i915_vkx_bind_pipeline(x, I915_VKX_ID_COLOR_PIPELINE);
	i915_vkx_bind_vertices(x);
	i915_vkx_bind_indices(x, 4U, VK_INDEX_TYPE_UINT16);
	i915_vkx_draw_indexed(x, 12U, 1U, 2U, 4, 0U);
	i915_vkx_record(x, I915_VKX_OP_END_RENDER_PASS);

	/* Runs it and compares the target with the two squares on black. */
	error = i915_vkx_finish(x, "INDEX16");
	if (error == 0) {
		i915_vkx_expect_clear(x);
		i915_vkx_expect_rect(x, 8U, 8U, 24U, 24U, I915_VKX_RED);
		i915_vkx_expect_rect(x, 40U, 40U, 56U, 56U, I915_VKX_GREEN);
		error = i915_vkx_compare_target(x, "INDEX16");
	}

	i915_vkx_verdict(x, "INDEX16", error);
}

/*
 * INDEX32: two indexed draws of the same six 32-bit indices pick their quad
 * with the vertex offset: 8 for the green square, then 4, two instances,
 * for the red one.
 */
static void
i915_vkx_step_index32(
	struct i915_vkx *x)
{
	int error;

	/* Records the pass, the colour pipeline, the buffers and the two draws. */
	i915_vkx_begin(x);
	i915_vkx_begin_pass(x);
	i915_vkx_bind_pipeline(x, I915_VKX_ID_COLOR_PIPELINE);
	i915_vkx_bind_vertices(x);
	i915_vkx_bind_indices(x, I915_VKX_INDEX32_OFFSET, VK_INDEX_TYPE_UINT32);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, 8, 0U);
	i915_vkx_draw_indexed(x, 6U, 2U, 0U, 4, 0U);
	i915_vkx_record(x, I915_VKX_OP_END_RENDER_PASS);

	/* Runs it and compares the target with the two squares on black. */
	error = i915_vkx_finish(x, "INDEX32");
	if (error == 0) {
		i915_vkx_expect_clear(x);
		i915_vkx_expect_rect(x, 8U, 8U, 24U, 24U, I915_VKX_RED);
		i915_vkx_expect_rect(x, 40U, 40U, 56U, 56U, I915_VKX_GREEN);
		error = i915_vkx_compare_target(x, "INDEX32");
	}

	i915_vkx_verdict(x, "INDEX32", error);
}

/*
 * VIEWPORT: a pipeline with dynamic viewport and scissor draws a quad that
 * covers its whole viewport twice.  The blue one in viewport (16, 8) 32x16
 * cut by scissor (0, 0) 40x64 covers columns 16..40, rows 8..24; the white
 * one in viewport (0, 40) 64x24 cut by scissor (8, 48) 16x8 covers columns
 * 8..24, rows 48..56.
 */
static void
i915_vkx_step_viewport(
	struct i915_vkx *x)
{
	int error;

	/* Records the pass, the dynamic pipeline and the buffers. */
	i915_vkx_begin(x);
	i915_vkx_begin_pass(x);
	i915_vkx_bind_pipeline(x, I915_VKX_ID_DYNAMIC_PIPELINE);
	i915_vkx_bind_vertices(x);
	i915_vkx_bind_indices(x, I915_VKX_INDEX32_OFFSET, VK_INDEX_TYPE_UINT32);

	/* The blue quad in the first viewport and scissor. */
	i915_vkx_set_viewport(x, I915_VKX_F_16, I915_VKX_F_8, I915_VKX_F_32, I915_VKX_F_16);
	i915_vkx_set_scissor(x, 0U, 0U, 40U, I915_VKX_SIZE);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, 0, 0U);

	/* The white quad in the second. */
	i915_vkx_set_viewport(x, I915_VKX_F_0, I915_VKX_F_40, I915_VKX_F_64, I915_VKX_F_24);
	i915_vkx_set_scissor(x, 8U, 48U, 16U, 8U);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, 12, 0U);
	i915_vkx_record(x, I915_VKX_OP_END_RENDER_PASS);

	/* Runs it and compares the target with the two clipped rectangles on black. */
	error = i915_vkx_finish(x, "VIEWPORT");
	if (error == 0) {
		i915_vkx_expect_clear(x);
		i915_vkx_expect_rect(x, 16U, 8U, 40U, 24U, I915_VKX_BLUE);
		i915_vkx_expect_rect(x, 8U, 48U, 24U, 56U, I915_VKX_WHITE);
		error = i915_vkx_compare_target(x, "VIEWPORT");
	}

	i915_vkx_verdict(x, "VIEWPORT", error);
}

/*
 * COPY: one vkCmdCopyBuffer of four regions, from 16 bytes to more than
 * four full rows of the copy, at offsets that are multiples of four but not
 * of the row; the destination must equal, byte for byte, the model the CPU
 * makes of it.
 */
static void
i915_vkx_step_copy(
	struct i915_vkx *x)
{
	static const uint64_t regions[4][3] = {
		{ 0U, 0U, 16U },
		{ 64U, 4100U, 3U * 16384U + 20U },
		{ 70000U, 60000U, 4U },
		{ 96000U, 90000U, 4U * 16384U + 4U },
	};
	uint32_t *source;
	uint8_t *destination;
	unsigned differ;
	unsigned first;
	unsigned index;
	int error;

	/* Fills the source with a pattern and the destination and its model with 0xcd. */
	source = (uint32_t *)(void *)(x->cpu + I915_VKX_SOURCE_OFFSET);
	destination = x->cpu + I915_VKX_DESTINATION_OFFSET;
	for (index = 0U; index < I915_VKX_COPY_BYTES / 4U; index++)
		source[index] = index * 0x9e3779b1U + 0x12345U;
	kern_memset(destination, 0xcd, I915_VKX_COPY_BYTES);
	kern_memset(x->model, 0xcd, I915_VKX_COPY_BYTES);
	drv_i915_gt_clflush(source, I915_VKX_COPY_BYTES);
	drv_i915_gt_clflush(destination, I915_VKX_COPY_BYTES);

	/* Records the copy: [src][dst][4][4]{src offset, dst offset, size}. */
	i915_vkx_begin(x);
	i915_vkx_record(x, I915_VKX_OP_COPY_BUFFER);
	i915_vkx_put64(x, I915_VKX_ID_SOURCE);
	i915_vkx_put64(x, I915_VKX_ID_DESTINATION);
	i915_vkx_put32(x, 4U);
	i915_vkx_put64(x, 4U);
	for (index = 0U; index < 4U; index++) {
		i915_vkx_put64(x, regions[index][0]);
		i915_vkx_put64(x, regions[index][1]);
		i915_vkx_put64(x, regions[index][2]);
	}

	/* Runs it. */
	error = i915_vkx_finish(x, "COPY");
	if (error != 0) {
		i915_vkx_verdict(x, "COPY", error);
		return;
	}

	/* Makes the model: every region copied on the CPU. */
	for (index = 0U; index < 4U; index++) {
		kern_memcpy(x->model + regions[index][1],
		       (const uint8_t *)source + regions[index][0],
		       (size_t)regions[index][2]);
	}

	/* Compares the destination with the model byte for byte. */
	drv_i915_gt_clflush(destination, I915_VKX_COPY_BYTES);
	differ = 0U;
	first = 0U;
	for (index = 0U; index < I915_VKX_COPY_BYTES; index++) {
		if (destination[index] != x->model[index]) {
			if (differ == 0U)
				first = index;
			differ++;
		}
	}

	/* Says where the bytes differ. */
	if (differ != 0U) {
		kern_logf("i915: vkx: COPY: %u of %u bytes differ; first at %u: 0x%02x, expected 0x%02x\n",
			  differ,
			  I915_VKX_COPY_BYTES,
			  first,
			  destination[first],
			  x->model[first]);
		error = EIO;
	}

	i915_vkx_verdict(x, "COPY", error);
}

/*
 * GRID: 64 cells of 8x8 pixels, each one push of the whole block (the
 * cell's offset for the vertex stage at byte 0, its colour for the
 * fragment stage at byte 112) and one indexed draw of the white cell quad:
 * 134 operations in one command buffer.  Cell c takes red, green and blue
 * levels c % 4, c / 4 % 4 and c / 16 of 0, 0.25, 0.75 and 1.
 */
static void
i915_vkx_step_grid(
	struct i915_vkx *x)
{
	uint32_t block[I915_VKX_PUSH_BYTES / 4U];
	uint32_t pixel;
	unsigned cell;
	unsigned column;
	unsigned row;
	int error;

	/* Records the pass, the pushed-colour pipeline and the buffers. */
	i915_vkx_begin(x);
	i915_vkx_begin_pass(x);
	i915_vkx_bind_pipeline(x, I915_VKX_ID_PUSH_PIPELINE);
	i915_vkx_bind_vertices(x);
	i915_vkx_bind_indices(x, I915_VKX_INDEX32_OFFSET, VK_INDEX_TYPE_UINT32);

	/* Records one push and one draw for each cell. */
	kern_memset(block, 0, sizeof(block));
	for (cell = 0U; cell < 64U; cell++) {
		/* The cell's offset: its column and row in steps of 0.25. */
		column = cell % 8U;
		row = cell / 8U;
		block[0] = i915_vkx_steps[column];
		block[1] = i915_vkx_steps[row];

		/* The cell's colour at byte 112, opaque. */
		block[I915_VKX_PUSH_COLOR / 4U + 0U] = i915_vkx_level_bits[cell % 4U];
		block[I915_VKX_PUSH_COLOR / 4U + 1U] = i915_vkx_level_bits[(cell / 4U) % 4U];
		block[I915_VKX_PUSH_COLOR / 4U + 2U] = i915_vkx_level_bits[cell / 16U];
		block[I915_VKX_PUSH_COLOR / 4U + 3U] = I915_VKX_F_1;

		i915_vkx_push(x, block);
		i915_vkx_draw_indexed(x, 6U, 1U, 0U, 16, 0U);
	}

	i915_vkx_record(x, I915_VKX_OP_END_RENDER_PASS);

	/* Runs it and compares the target with the 64 coloured cells. */
	error = i915_vkx_finish(x, "GRID");
	if (error == 0) {
		i915_vkx_expect_clear(x);
		for (cell = 0U; cell < 64U; cell++) {
			/* The cell's pixel: red, green and blue bytes of its levels, opaque. */
			pixel = i915_vkx_level_bytes[cell % 4U] |
			    (i915_vkx_level_bytes[(cell / 4U) % 4U] << 8) |
			    (i915_vkx_level_bytes[cell / 16U] << 16) |
			    0xff000000U;
			column = cell % 8U;
			row = cell / 8U;
			i915_vkx_expect_rect(x, column * 8U, row * 8U, column * 8U + 8U, row * 8U + 8U, pixel);
		}

		error = i915_vkx_compare_target(x, "GRID");
	}

	i915_vkx_verdict(x, "GRID", error);
}

/*
 * Describes the mip steps' objects: the texture and the chain, 64x64 RGBA8
 * images of all 7 levels laid out as the executor lays out a created image;
 * the texturing pipeline; a view of every level and one of level 2 on; the
 * seven samplers and the eight sets that pair a view with a sampler.
 */
static void
i915_vkx_mip_objects_init(
	struct i915_vkx *x)
{
	/* The texture the draws sample, laid out by the executor's own layout. */
	x->texture.format = VK_FORMAT_R8G8B8A8_UNORM;
	x->texture.width = I915_VKX_MIP_SIZE;
	x->texture.height = I915_VKX_MIP_SIZE;
	x->texture.usage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;
	x->texture.levels = I915_VKX_MIP_LEVELS;
	(void)drv_i915_gfx_image_layout(&x->texture);
	x->texture.memory = &x->memory;
	x->texture.offset = I915_VKX_TEXTURE_OFFSET;

	/* The chain the blits fill, level after level, laid out the same way. */
	x->chain.format = VK_FORMAT_R8G8B8A8_UNORM;
	x->chain.width = I915_VKX_MIP_SIZE;
	x->chain.height = I915_VKX_MIP_SIZE;
	x->chain.usage = VK_IMAGE_USAGE_TRANSFER_SRC_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT;
	x->chain.levels = I915_VKX_MIP_LEVELS;
	(void)drv_i915_gfx_image_layout(&x->chain);
	x->chain.memory = &x->memory;
	x->chain.offset = I915_VKX_CHAIN_OFFSET;

	/* The texturing shader borrows the generated words; its pipeline places vertices as the others do. */
	x->tex.words = (uint32_t *)(uintptr_t)i915_vkx_tex_frag;
	x->tex.word_count = sizeof(i915_vkx_tex_frag) / 4U;
	i915_vkx_pipeline_init(x, &x->tex_pipeline, &x->tex, 0);

	/* A view of every level of the texture. */
	x->texture_view.image = &x->texture;
	x->texture_view.format = VK_FORMAT_R8G8B8A8_UNORM;
	x->texture_view.base_level = 0U;
	x->texture_view.level_count = I915_VKX_MIP_LEVELS;

	/* A view of level 2 on, whose first level is 16x16. */
	x->later_view.image = &x->texture;
	x->later_view.format = VK_FORMAT_R8G8B8A8_UNORM;
	x->later_view.base_level = 2U;
	x->later_view.level_count = I915_VKX_MIP_LEVELS - 2U;

	/* The nearest level over the whole LOD range; LOD fixed at 1.5 and blended; the nearest level with bias 2. */
	i915_vkx_mip_sampler_init(&x->nearest_sampler, VK_SAMPLER_MIPMAP_MODE_NEAREST, I915_VKX_F_0, I915_VKX_F_0, I915_VKX_F_16);
	i915_vkx_mip_sampler_init(&x->forced_sampler, VK_SAMPLER_MIPMAP_MODE_LINEAR, I915_VKX_F_0, I915_VKX_F_ONE_AND_HALF, I915_VKX_F_ONE_AND_HALF);
	i915_vkx_mip_sampler_init(&x->bias_sampler, VK_SAMPLER_MIPMAP_MODE_NEAREST, I915_VKX_F_2, I915_VKX_F_0, I915_VKX_F_16);

	/* Linear blending over the whole LOD range; the least LOD held at 5 (nearest), 5.5 (blended) and 6 (nearest). */
	i915_vkx_mip_sampler_init(&x->linear_sampler, VK_SAMPLER_MIPMAP_MODE_LINEAR, I915_VKX_F_0, I915_VKX_F_0, I915_VKX_F_16);
	i915_vkx_mip_sampler_init(&x->lod5_sampler, VK_SAMPLER_MIPMAP_MODE_NEAREST, I915_VKX_F_0, I915_VKX_F_5, I915_VKX_F_16);
	i915_vkx_mip_sampler_init(&x->lod5_half_sampler, VK_SAMPLER_MIPMAP_MODE_LINEAR, I915_VKX_F_0, I915_VKX_F_FIVE_AND_HALF, I915_VKX_F_16);
	i915_vkx_mip_sampler_init(&x->lod6_sampler, VK_SAMPLER_MIPMAP_MODE_NEAREST, I915_VKX_F_0, I915_VKX_F_6, I915_VKX_F_16);

	/* The sets: binding 0 is the one sampled image of the texturing shader. */
	x->nearest_set.slots[0].view = &x->texture_view;
	x->nearest_set.slots[0].sampler = &x->nearest_sampler;
	x->forced_set.slots[0].view = &x->texture_view;
	x->forced_set.slots[0].sampler = &x->forced_sampler;
	x->bias_set.slots[0].view = &x->texture_view;
	x->bias_set.slots[0].sampler = &x->bias_sampler;
	x->later_set.slots[0].view = &x->later_view;
	x->later_set.slots[0].sampler = &x->nearest_sampler;
	x->linear_set.slots[0].view = &x->texture_view;
	x->linear_set.slots[0].sampler = &x->linear_sampler;
	x->lod5_set.slots[0].view = &x->texture_view;
	x->lod5_set.slots[0].sampler = &x->lod5_sampler;
	x->lod5_half_set.slots[0].view = &x->texture_view;
	x->lod5_half_set.slots[0].sampler = &x->lod5_half_sampler;
	x->lod6_set.slots[0].view = &x->texture_view;
	x->lod6_set.slots[0].sampler = &x->lod6_sampler;
}

/* Describes a sampler with linear filters that clamps to the edge, with a mipmap mode, a bias and a LOD range as float bits. */
static void
i915_vkx_mip_sampler_init(
	struct i915_gfx_sampler *sampler,
	uint32_t mipmap_mode,
	uint32_t lod_bias,
	uint32_t min_lod,
	uint32_t max_lod)
{
	/* Linear within a level, clamped to the edge. */
	kern_memset(sampler, 0, sizeof(*sampler));
	sampler->mag_filter = VK_FILTER_LINEAR;
	sampler->min_filter = VK_FILTER_LINEAR;
	sampler->address_u = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
	sampler->address_v = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;

	/* How the level is chosen. */
	sampler->mipmap_mode = mipmap_mode;
	sampler->lod_bias = lod_bias;
	sampler->min_lod = min_lod;
	sampler->max_lod = max_lod;
}

/*
 * Writes the four vertices of an axis-aligned quad between NDC steps
 * (left, top) and (right, bottom) whose colour is the texture coordinate:
 * (0, 0) at the top left, (1, 1) at the bottom right.
 */
static void
i915_vkx_texquad_write(
	uint32_t *words,
	unsigned left,
	unsigned top,
	unsigned right,
	unsigned bottom)
{
	unsigned corner;
	unsigned x;
	unsigned y;
	uint32_t u;
	uint32_t v;

	/* Writes the corners in turn: top left, top right, bottom right, bottom left. */
	for (corner = 0U; corner < 4U; corner++) {
		/* The right corners are the second and third, the bottom ones the third and fourth. */
		x = left;
		u = I915_VKX_F_0;
		if (corner == 1U || corner == 2U) {
			x = right;
			u = I915_VKX_F_1;
		}
		y = top;
		v = I915_VKX_F_0;
		if (corner >= 2U) {
			y = bottom;
			v = I915_VKX_F_1;
		}

		/* The position (x, y, 0, 1), then the coordinate (u, v, 0, 1). */
		words[corner * 8U + 0U] = i915_vkx_ndc[x];
		words[corner * 8U + 1U] = i915_vkx_ndc[y];
		words[corner * 8U + 2U] = I915_VKX_F_0;
		words[corner * 8U + 3U] = I915_VKX_F_1;
		words[corner * 8U + 4U] = u;
		words[corner * 8U + 5U] = v;
		words[corner * 8U + 6U] = I915_VKX_F_0;
		words[corner * 8U + 7U] = I915_VKX_F_1;
	}
}

/* Reports the width and the height of a level of the mip steps' square images. */
static uint32_t
i915_vkx_level_extent(
	uint32_t level)
{
	uint32_t extent;

	/* Halves the side once for each level, down to one texel. */
	extent = I915_VKX_MIP_SIZE >> level;
	if (extent == 0U)
		extent = 1U;

	/* Succeeded: the side of the level. */
	return extent;
}

/* Appends a VkImageSubresourceLayers of one colour level: [aspect][level][first layer][layers]. */
static void
i915_vkx_subresource(
	struct i915_vkx *x,
	uint32_t level)
{
	/* The colour aspect of the level's one layer. */
	i915_vkx_put32(x, VK_IMAGE_ASPECT_COLOR_BIT);
	i915_vkx_put32(x, level);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 1U);
}

/*
 * Appends a vkCmdCopyBufferToImage from the source buffer, or a
 * vkCmdCopyImageToBuffer into the destination buffer, of one whole level
 * packed at `buffer_offset`: [buffer][image][layout] or [image][layout]
 * [buffer], then [1][1]{offset, row length, image height, level, image
 * offset, extent}.
 */
static void
i915_vkx_level_copy(
	struct i915_vkx *x,
	uint32_t opcode,
	uint64_t image,
	uint32_t level,
	uint64_t buffer_offset)
{
	uint32_t extent;

	/* The buffer and the image in the direction's order. */
	i915_vkx_record(x, opcode);
	if (opcode == I915_VKX_OP_COPY_BUFFER_TO_IMAGE) {
		i915_vkx_put64(x, I915_VKX_ID_SOURCE);
		i915_vkx_put64(x, image);
		i915_vkx_put32(x, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
	} else {
		i915_vkx_put64(x, image);
		i915_vkx_put32(x, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL);
		i915_vkx_put64(x, I915_VKX_ID_DESTINATION);
	}

	/* One region: the buffer offset, packed rows, the level at (0, 0), the level's extent. */
	extent = i915_vkx_level_extent(level);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put64(x, buffer_offset);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_subresource(x, level);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, extent);
	i915_vkx_put32(x, extent);
	i915_vkx_put32(x, 1U);
}

/*
 * Appends a vkCmdBlitImage of the whole of level - 1 into the whole of
 * `level` of the same image with a linear filter: [src][layout][dst]
 * [layout][1][1]{src level, [2] corners, dst level, [2] corners}[filter].
 */
static void
i915_vkx_level_blit(
	struct i915_vkx *x,
	uint64_t image,
	uint32_t level)
{
	/* The image twice, as source and destination. */
	i915_vkx_record(x, I915_VKX_OP_BLIT_IMAGE);
	i915_vkx_put64(x, image);
	i915_vkx_put32(x, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL);
	i915_vkx_put64(x, image);
	i915_vkx_put32(x, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);

	/* The source: the level above, from (0, 0, 0) to its far corner. */
	i915_vkx_subresource(x, level - 1U);
	i915_vkx_put64(x, 2U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, i915_vkx_level_extent(level - 1U));
	i915_vkx_put32(x, i915_vkx_level_extent(level - 1U));
	i915_vkx_put32(x, 1U);

	/* The destination: the level, from (0, 0, 0) to its far corner. */
	i915_vkx_subresource(x, level);
	i915_vkx_put64(x, 2U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, i915_vkx_level_extent(level));
	i915_vkx_put32(x, i915_vkx_level_extent(level));
	i915_vkx_put32(x, 1U);

	/* The filter. */
	i915_vkx_put32(x, VK_FILTER_LINEAR);
}

/* Appends vkCmdBindDescriptorSets of one set as set 0: [bind point][layout][first][1][1]{set}[0][0]. */
static void
i915_vkx_bind_set(
	struct i915_vkx *x,
	uint64_t set)
{
	/* The graphics bind point, no layout, set 0, one set, no dynamic offsets. */
	i915_vkx_record(x, I915_VKX_OP_BIND_DESCRIPTOR_SETS);
	i915_vkx_put32(x, VK_PIPELINE_BIND_POINT_GRAPHICS);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put64(x, set);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, 0U);
}

/*
 * Fills each level of the source buffer's staging area with the level's
 * colour and appends the per-level copies that upload them into the
 * texture, level 0 first.
 */
static void
i915_vkx_texture_fill(
	struct i915_vkx *x)
{
	uint32_t *staging;
	uint64_t offset;
	uint32_t level;
	uint32_t texels;
	uint32_t index;

	/* Stages every level, packed one after another, and uploads it. */
	staging = (uint32_t *)(void *)(x->cpu + I915_VKX_SOURCE_OFFSET);
	offset = 0U;
	for (level = 0U; level < I915_VKX_MIP_LEVELS; level++) {
		/* Fills the level's texels with its colour. */
		texels = i915_vkx_level_extent(level) * i915_vkx_level_extent(level);
		for (index = 0U; index < texels; index++)
			staging[offset / 4U + index] = i915_vkx_level_colors[level];

		/* Uploads the level from where it is staged. */
		i915_vkx_level_copy(x, I915_VKX_OP_COPY_BUFFER_TO_IMAGE, I915_VKX_ID_TEXTURE, level, offset);
		offset += (uint64_t)texels * 4U;
	}

	/* Writes the staged levels back to memory before the GPU reads them. */
	drv_i915_gt_clflush(staging, (size_t)offset);
}

/* Reports the pixel halfway between two pixels, channel by channel, rounded half up. */
static uint32_t
i915_vkx_blend(
	uint32_t first,
	uint32_t second)
{
	uint32_t pixel;
	uint32_t shift;
	uint32_t channel;

	/* Averages each of the four bytes. */
	pixel = 0U;
	for (shift = 0U; shift < 32U; shift += 8U) {
		channel = (((first >> shift) & 0xffU) + ((second >> shift) & 0xffU) + 1U) / 2U;
		pixel |= channel << shift;
	}

	/* Succeeded: the blended pixel. */
	return pixel;
}

/* Decides whether every byte of a pixel is within the mip tolerance of the expected pixel's byte. */
static int
i915_vkx_near(
	uint32_t pixel,
	uint32_t expected)
{
	uint32_t shift;
	uint32_t have;
	uint32_t want;

	/* Compares each of the four bytes. */
	for (shift = 0U; shift < 32U; shift += 8U) {
		have = (pixel >> shift) & 0xffU;
		want = (expected >> shift) & 0xffU;
		if (have > want + I915_VKX_MIP_TOLERANCE)
			return 0;
		if (want > have + I915_VKX_MIP_TOLERANCE)
			return 0;
	}

	/* Succeeded: every byte is near. */
	return 1;
}

/* Compares the target with the expected image, each byte within the mip tolerance; EIO with the first difference logged. */
static int
i915_vkx_compare_near(
	struct i915_vkx *x,
	const char *what)
{
	const uint32_t *pixels;
	unsigned differ;
	unsigned first;
	unsigned index;
	int near;

	/* Reads the target through the CPU view, past any line the CPU still caches. */
	pixels = (const uint32_t *)(const void *)(x->cpu + I915_VKX_TARGET_OFFSET);
	drv_i915_gt_clflush(pixels, I915_VKX_SIZE * I915_VKX_SIZE * 4U);

	/* Counts the pixels that are not near and notes the first. */
	differ = 0U;
	first = 0U;
	for (index = 0U; index < I915_VKX_SIZE * I915_VKX_SIZE; index++) {
		near = i915_vkx_near(pixels[index], x->expected[index]);
		if (near == 0) {
			if (differ == 0U)
				first = index;
			differ++;
		}
	}

	/* Says where the image differs. */
	if (differ != 0U) {
		kern_logf("i915: vkx: %s: %u of %u pixels differ; first at (%u,%u): 0x%08x, expected 0x%08x\n",
			  what,
			  differ,
			  I915_VKX_SIZE * I915_VKX_SIZE,
			  first % I915_VKX_SIZE,
			  first / I915_VKX_SIZE,
			  pixels[first],
			  x->expected[first]);
		return EIO;
	}

	/* Succeeded: every pixel is near its expected value. */
	return 0;
}

/*
 * MIP-NEAREST: the texture's seven levels are uploaded by per-level copies,
 * each in its own colour, and sampled with the nearest level through quads
 * of 32, 16 and 8 pixels: the texture minified two, four and eight times
 * shows levels 1, 2 and 3.
 */
static void
i915_vkx_step_mip_nearest(
	struct i915_vkx *x)
{
	int error;

	/* Records the upload, then the pass with the three quads sampled nearest. */
	i915_vkx_begin(x);
	i915_vkx_texture_fill(x);
	i915_vkx_begin_pass(x);
	i915_vkx_bind_pipeline(x, I915_VKX_ID_TEX_PIPELINE);
	i915_vkx_bind_vertices(x);
	i915_vkx_bind_indices(x, I915_VKX_INDEX32_OFFSET, VK_INDEX_TYPE_UINT32);
	i915_vkx_bind_set(x, I915_VKX_ID_SET_NEAREST);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST, 0U);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 4, 0U);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 8, 0U);
	i915_vkx_record(x, I915_VKX_OP_END_RENDER_PASS);

	/* Runs it and compares the target with the three quads in the colours of levels 1, 2 and 3. */
	error = i915_vkx_finish(x, "MIP-NEAREST");
	if (error == 0) {
		i915_vkx_expect_clear(x);
		i915_vkx_expect_rect(x, 0U, 0U, 32U, 32U, i915_vkx_level_colors[1]);
		i915_vkx_expect_rect(x, 32U, 0U, 48U, 16U, i915_vkx_level_colors[2]);
		i915_vkx_expect_rect(x, 48U, 0U, 56U, 8U, i915_vkx_level_colors[3]);
		error = i915_vkx_compare_near(x, "MIP-NEAREST");
	}

	i915_vkx_verdict(x, "MIP-NEAREST", error);
}

/*
 * MIP-LINEAR: a sampler whose LOD range is [1.5, 1.5] blends levels 1 and
 * 2 half and half with the linear mip filter; a sampler with LOD bias 2
 * reads level 3 through a quad that shows level 1 unbiased; a view of level
 * 2 on reads its first level (the texture's level 2) through a quad of that
 * level's size.  The linear mip filter over the whole LOD range shows level
 * 2 alone through a quad minified exactly four times; a least LOD of 5 and
 * of 6 shows the two smallest levels (2x2 and 1x1) through quads that are
 * minified only eight times, and a least LOD of 5.5 blends them.
 */
static void
i915_vkx_step_mip_linear(
	struct i915_vkx *x)
{
	int error;

	/* Records the upload, then the pass with one quad for each sampler and view. */
	i915_vkx_begin(x);
	i915_vkx_texture_fill(x);
	i915_vkx_begin_pass(x);
	i915_vkx_bind_pipeline(x, I915_VKX_ID_TEX_PIPELINE);
	i915_vkx_bind_vertices(x);
	i915_vkx_bind_indices(x, I915_VKX_INDEX32_OFFSET, VK_INDEX_TYPE_UINT32);

	/* The 32-pixel quad at the top left with the LOD held at 1.5. */
	i915_vkx_bind_set(x, I915_VKX_ID_SET_FORCED);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST, 0U);

	/* The 32-pixel quad at the bottom right with bias 2. */
	i915_vkx_bind_set(x, I915_VKX_ID_SET_BIAS);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 12, 0U);

	/* The 16-pixel quad at the left through the view of level 2 on. */
	i915_vkx_bind_set(x, I915_VKX_ID_SET_LATER);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 16, 0U);

	/* The 16-pixel quad at the top with linear blending at its natural LOD of 2. */
	i915_vkx_bind_set(x, I915_VKX_ID_SET_LINEAR);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 4, 0U);

	/* The three 8-pixel quads at the top right with the least LOD at 5, 5.5 and 6. */
	i915_vkx_bind_set(x, I915_VKX_ID_SET_LOD5);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 8, 0U);
	i915_vkx_bind_set(x, I915_VKX_ID_SET_LOD5_HALF);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 20, 0U);
	i915_vkx_bind_set(x, I915_VKX_ID_SET_LOD6);
	i915_vkx_draw_indexed(x, 6U, 1U, 0U, (int32_t)I915_VKX_TEXQUAD_FIRST + 24, 0U);
	i915_vkx_record(x, I915_VKX_OP_END_RENDER_PASS);

	/*
	 * Runs it and compares: the blend of levels 1 and 2, level 3, level 2;
	 * level 2; level 5, the blend of levels 5 and 6, level 6.
	 */
	error = i915_vkx_finish(x, "MIP-LINEAR");
	if (error == 0) {
		i915_vkx_expect_clear(x);
		i915_vkx_expect_rect(x, 0U, 0U, 32U, 32U, i915_vkx_blend(i915_vkx_level_colors[1], i915_vkx_level_colors[2]));
		i915_vkx_expect_rect(x, 32U, 32U, 64U, 64U, i915_vkx_level_colors[3]);
		i915_vkx_expect_rect(x, 0U, 32U, 16U, 48U, i915_vkx_level_colors[2]);
		i915_vkx_expect_rect(x, 32U, 0U, 48U, 16U, i915_vkx_level_colors[2]);
		i915_vkx_expect_rect(x, 48U, 0U, 56U, 8U, i915_vkx_level_colors[5]);
		i915_vkx_expect_rect(x, 56U, 0U, 64U, 8U, i915_vkx_blend(i915_vkx_level_colors[5], i915_vkx_level_colors[6]));
		i915_vkx_expect_rect(x, 56U, 8U, 64U, 16U, i915_vkx_level_colors[6]);
		error = i915_vkx_compare_near(x, "MIP-LINEAR");
	}

	i915_vkx_verdict(x, "MIP-LINEAR", error);
}

/*
 * MIP-BLIT: level 0 of the chain is uploaded with a pattern, each further
 * level is made by a linear vkCmdBlitImage from the level above in the same
 * image, and every level is copied out.  Level 0 must come back exactly;
 * every texel of level n + 1 must be the box filter (the rounded mean of
 * the 2x2 texels above it) of level n as it came back, each byte within the
 * mip tolerance.
 */
static void
i915_vkx_step_mip_blit(
	struct i915_vkx *x)
{
	const uint32_t *above;
	const uint32_t *level_texels;
	uint32_t *staging;
	uint32_t *readback;
	uint64_t offset;
	uint64_t above_offset;
	uint32_t level;
	uint32_t extent;
	uint32_t column;
	uint32_t row;
	uint32_t texel;
	uint32_t shift;
	uint32_t sum;
	uint32_t expected;
	uint32_t pattern;
	unsigned differ;
	unsigned first_level;
	unsigned first_texel;
	uint32_t first_have;
	uint32_t first_want;
	int near;
	int error;

	/* Stages level 0: red across, green down, blue a coarse diagonal ripple, opaque. */
	staging = (uint32_t *)(void *)(x->cpu + I915_VKX_SOURCE_OFFSET);
	for (row = 0U; row < I915_VKX_MIP_SIZE; row++) {
		for (column = 0U; column < I915_VKX_MIP_SIZE; column++) {
			staging[row * I915_VKX_MIP_SIZE + column] = (column * 4U) |
			    ((row * 4U) << 8) |
			    ((((column * 3U + row * 5U) & 63U) * 4U) << 16) |
			    0xff000000U;
		}
	}
	drv_i915_gt_clflush(staging, I915_VKX_MIP_SIZE * I915_VKX_MIP_SIZE * 4U);

	/* Clears the readback area so that a level never written cannot pass. */
	readback = (uint32_t *)(void *)(x->cpu + I915_VKX_DESTINATION_OFFSET);
	kern_memset(readback, 0, I915_VKX_COPY_BYTES);
	drv_i915_gt_clflush(readback, I915_VKX_COPY_BYTES);

	/* Records the upload of level 0 and the blit of every further level from the one above. */
	i915_vkx_begin(x);
	i915_vkx_level_copy(x, I915_VKX_OP_COPY_BUFFER_TO_IMAGE, I915_VKX_ID_CHAIN, 0U, 0U);
	for (level = 1U; level < I915_VKX_MIP_LEVELS; level++)
		i915_vkx_level_blit(x, I915_VKX_ID_CHAIN, level);

	/* Records the copy of every level out, packed one after another. */
	offset = 0U;
	for (level = 0U; level < I915_VKX_MIP_LEVELS; level++) {
		i915_vkx_level_copy(x, I915_VKX_OP_COPY_IMAGE_TO_BUFFER, I915_VKX_ID_CHAIN, level, offset);
		offset += (uint64_t)i915_vkx_level_extent(level) * i915_vkx_level_extent(level) * 4U;
	}

	/* Runs it. */
	error = i915_vkx_finish(x, "MIP-BLIT");
	if (error != 0) {
		i915_vkx_verdict(x, "MIP-BLIT", error);
		return;
	}

	/* Reads the levels back past any line the CPU still caches. */
	drv_i915_gt_clflush(readback, (size_t)offset);

	/* Level 0 comes back exactly as staged. */
	differ = 0U;
	first_level = 0U;
	first_texel = 0U;
	first_have = 0U;
	first_want = 0U;
	for (texel = 0U; texel < I915_VKX_MIP_SIZE * I915_VKX_MIP_SIZE; texel++) {
		pattern = staging[texel];
		if (readback[texel] != pattern) {
			if (differ == 0U) {
				first_texel = texel;
				first_have = readback[texel];
				first_want = pattern;
			}
			differ++;
		}
	}

	/* Every further level is the box filter of the level above it as it came back. */
	above_offset = 0U;
	offset = (uint64_t)I915_VKX_MIP_SIZE * I915_VKX_MIP_SIZE * 4U;
	for (level = 1U; level < I915_VKX_MIP_LEVELS; level++) {
		/* Locates the level and the level above in the readback. */
		above = readback + above_offset / 4U;
		level_texels = readback + offset / 4U;
		extent = i915_vkx_level_extent(level);

		/* Compares every texel with the rounded mean of the four above it. */
		for (row = 0U; row < extent; row++) {
			for (column = 0U; column < extent; column++) {
				/* Averages each byte of the 2x2 texels above. */
				expected = 0U;
				for (shift = 0U; shift < 32U; shift += 8U) {
					sum = ((above[(row * 2U) * extent * 2U + column * 2U] >> shift) & 0xffU) +
					    ((above[(row * 2U) * extent * 2U + column * 2U + 1U] >> shift) & 0xffU) +
					    ((above[(row * 2U + 1U) * extent * 2U + column * 2U] >> shift) & 0xffU) +
					    ((above[(row * 2U + 1U) * extent * 2U + column * 2U + 1U] >> shift) & 0xffU);
					expected |= ((sum + 2U) / 4U) << shift;
				}

				/* Counts a texel that is not near and notes the first. */
				near = i915_vkx_near(level_texels[row * extent + column], expected);
				if (near == 0) {
					if (differ == 0U) {
						first_level = level;
						first_texel = row * extent + column;
						first_have = level_texels[row * extent + column];
						first_want = expected;
					}
					differ++;
				}
			}
		}

		/* Moves on: this level is the next one's level above. */
		above_offset = offset;
		offset += (uint64_t)extent * extent * 4U;
	}

	/* Says where the chain differs. */
	if (differ != 0U) {
		kern_logf("i915: vkx: MIP-BLIT: %u texels differ; first in level %u at texel %u: 0x%08x, expected 0x%08x\n",
			  differ,
			  first_level,
			  first_texel,
			  first_have,
			  first_want);
		error = EIO;
	}

	i915_vkx_verdict(x, "MIP-BLIT", error);
}
