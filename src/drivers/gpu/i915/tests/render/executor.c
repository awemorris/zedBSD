/*
 * The executor scenario "vkx": command buffers recorded through the wire
 * and run on the GPU, checked against images and bytes the CPU computes.
 *
 * The executor runs its GPU work on the request worker, which serves only
 * once the node is published, so the scenario starts a thread and returns;
 * the thread waits for the node, opens a session of its own as a client
 * would, and drives the executor with the wire commands libvulkan sends.
 * The objects a command buffer names (the storage, buffers, target, render
 * pass, framebuffer and pipelines) are made directly and published in the
 * executor's object table, so each step exercises the recording and its
 * execution: indexed draws with 16- and 32-bit indices, a vertex offset and
 * a first index; dynamic viewports and scissors; buffer copies; a command
 * buffer of well over 64 operations whose fragment shader reads the pushed
 * colour at byte 112; a mipmapped texture whose levels are filled with
 * distinct colours by per-level copies and sampled minified with nearest
 * and linear mip filtering, a LOD range, a LOD bias and a view of later
 * levels; a mip chain generated by linear blits from level to level.  Each
 * step logs "VKX-<name> PASS" or "FAIL", then the thread logs the verdict
 * and closes the session.
 */

