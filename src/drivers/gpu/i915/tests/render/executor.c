/*
 * Describes one pipeline: the placing vertex shader with a fragment shader,
 * two vec4 attributes of one binding, a triangle list, no culling and no
 * depth; the whole target as viewport and scissor, or both dynamic.
 */
static void
i915_vkx_pipeline_init(
	struct i915_vkx *x,
	struct i915_gfx_pipeline *pipeline,
	struct i915_gfx_shader *fragment,
	int dynamic)
{
	/* The two stages. */
	kern_memset(pipeline, 0, sizeof(*pipeline));
	pipeline->vertex = &x->place;
	pipeline->fragment = fragment;

	/* Binding 0 of 32-byte vertices: the position at 0, the colour at 16. */
	pipeline->binding_count = 1U;
	pipeline->bindings[0].binding = 0U;
	pipeline->bindings[0].stride = I915_VKX_VERTEX_STRIDE;
	pipeline->attribute_count = 2U;
	pipeline->attributes[0].location = 0U;
	pipeline->attributes[0].binding = 0U;
	pipeline->attributes[0].format = VK_FORMAT_R32G32B32A32_SFLOAT;
	pipeline->attributes[0].offset = 0U;
	pipeline->attributes[1].location = 1U;
	pipeline->attributes[1].binding = 0U;
	pipeline->attributes[1].format = VK_FORMAT_R32G32B32A32_SFLOAT;
	pipeline->attributes[1].offset = 16U;

	/* A triangle list, drawn from both sides with no depth test. */
	pipeline->topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;
	pipeline->cull_mode = VK_CULL_MODE_NONE;

	/* A dynamic pipeline leaves its viewport and scissor to the command buffer. */
	if (dynamic != 0) {
		pipeline->dynamic_viewport = 1;
		pipeline->dynamic_scissor = 1;
		return;
	}

	/* The whole target, depth range [0, 1]. */
	pipeline->viewport[0] = I915_VKX_F_0;
	pipeline->viewport[1] = I915_VKX_F_0;
	pipeline->viewport[2] = I915_VKX_F_64;
	pipeline->viewport[3] = I915_VKX_F_64;
	pipeline->viewport[4] = I915_VKX_F_0;
	pipeline->viewport[5] = I915_VKX_F_1;
	pipeline->scissor.extent.width = I915_VKX_SIZE;
	pipeline->scissor.extent.height = I915_VKX_SIZE;
}

/* Compiles the four pipelines' kernels with the executor's compiler. */
static int
i915_vkx_pipelines_prepare(
	struct i915_vkx *x)
{
	int error;

	/* The colour pipeline. */
	error = drv_i915_gfx_pipeline_prepare(x->render, &x->color_pipeline);
	if (error != 0)
		return error;

	/* The pipeline with dynamic viewport and scissor. */
	error = drv_i915_gfx_pipeline_prepare(x->render, &x->dynamic_pipeline);
	if (error != 0)
		return error;

	/* The pipeline whose fragment shader reads the pushed colour. */
	error = drv_i915_gfx_pipeline_prepare(x->render, &x->push_pipeline);
	if (error != 0)
		return error;

	/* The pipeline whose fragment shader samples the mipmapped texture. */
	error = drv_i915_gfx_pipeline_prepare(x->render, &x->tex_pipeline);
	if (error != 0)
		return error;

	/* Says what the pushed-colour pipeline reads, which the grid step relies on. */
	kern_logf("i915: vkx: push registers: vertex %u, fragment %u\n",
		  x->push_pipeline.vs_binary->push_regs,
		  x->push_pipeline.fs_binary->push_regs);

	/* Succeeded: every pipeline can draw. */
	return 0;
}

/*
 * Writes the vertex buffer: five quads of four vertices each.
 *
 *   0..3    the whole target, blue
 *   4..7    pixels 8..24 square, red
 *   8..11   pixels 40..56 square, green
 *   12..15  the whole target, white
 *   16..19  pixels 0..8 square (grid cell 0), white
 *
 * then, from vertex 32 on, seven textured quads whose colour carries the
 * texture coordinate, (0, 0) at the top left to (1, 1) at the bottom right:
 *
 *   32..35  pixels 0..32 square (the texture minified twice)
 *   36..39  columns 32..48, rows 0..16 (four times)
 *   40..43  columns 48..56, rows 0..8 (eight times)
 *   44..47  pixels 32..64 square (twice)
 *   48..51  columns 0..16, rows 32..48 (four times)
 *   52..55  columns 56..64, rows 0..8 (eight times)
 *   56..59  columns 56..64, rows 8..16 (eight times)
 */
static void
i915_vkx_vertices_write(
	struct i915_vkx *x)
{
	static const uint32_t blue[4] = { I915_VKX_F_0, I915_VKX_F_0, I915_VKX_F_1, I915_VKX_F_1 };
	static const uint32_t red[4] = { I915_VKX_F_1, I915_VKX_F_0, I915_VKX_F_0, I915_VKX_F_1 };
	static const uint32_t green[4] = { I915_VKX_F_0, I915_VKX_F_1, I915_VKX_F_0, I915_VKX_F_1 };
	static const uint32_t white[4] = { I915_VKX_F_1, I915_VKX_F_1, I915_VKX_F_1, I915_VKX_F_1 };
	uint32_t *words;

	/* Writes the five quads, eight words to a vertex. */
	words = (uint32_t *)(void *)(x->cpu + I915_VKX_VERTEX_OFFSET);
	i915_vkx_quad_write(words, 0U, 0U, 8U, 8U, blue);
	i915_vkx_quad_write(words + 32U, 1U, 1U, 3U, 3U, red);
	i915_vkx_quad_write(words + 64U, 5U, 5U, 7U, 7U, green);
	i915_vkx_quad_write(words + 96U, 0U, 0U, 8U, 8U, white);
	i915_vkx_quad_write(words + 128U, 0U, 0U, 1U, 1U, white);

	/* Writes the seven textured quads. */
	i915_vkx_texquad_write(words + I915_VKX_TEXQUAD_FIRST * 8U, 0U, 0U, 4U, 4U);
	i915_vkx_texquad_write(words + (I915_VKX_TEXQUAD_FIRST + 4U) * 8U, 4U, 0U, 6U, 2U);
	i915_vkx_texquad_write(words + (I915_VKX_TEXQUAD_FIRST + 8U) * 8U, 6U, 0U, 7U, 1U);
	i915_vkx_texquad_write(words + (I915_VKX_TEXQUAD_FIRST + 12U) * 8U, 4U, 4U, 8U, 8U);
	i915_vkx_texquad_write(words + (I915_VKX_TEXQUAD_FIRST + 16U) * 8U, 0U, 4U, 2U, 6U);
	i915_vkx_texquad_write(words + (I915_VKX_TEXQUAD_FIRST + 20U) * 8U, 7U, 0U, 8U, 1U);
	i915_vkx_texquad_write(words + (I915_VKX_TEXQUAD_FIRST + 24U) * 8U, 7U, 1U, 8U, 2U);

	/* Writes the vertices back to memory before the GPU reads them. */
	drv_i915_gt_clflush(words, I915_VKX_VERTEX_BYTES);
}

/* Writes the four vertices of an axis-aligned quad between NDC steps (left, top) and (right, bottom). */
static void
i915_vkx_quad_write(
	uint32_t *words,
	unsigned left,
	unsigned top,
	unsigned right,
	unsigned bottom,
	const uint32_t color[4])
{
	unsigned corner;
	unsigned x;
	unsigned y;

	/* Writes the corners in turn: top left, top right, bottom right, bottom left. */
	for (corner = 0U; corner < 4U; corner++) {
		/* The right corners are the second and third, the bottom ones the third and fourth. */
		x = left;
		if (corner == 1U || corner == 2U)
			x = right;
		y = top;
		if (corner >= 2U)
			y = bottom;

		/* The position (x, y, 0, 1), then the colour. */
		words[corner * 8U + 0U] = i915_vkx_ndc[x];
		words[corner * 8U + 1U] = i915_vkx_ndc[y];
		words[corner * 8U + 2U] = I915_VKX_F_0;
		words[corner * 8U + 3U] = I915_VKX_F_1;
		kern_memcpy(&words[corner * 8U + 4U], color, 4U * sizeof(color[0]));
	}
}

/*
 * Writes the index buffer.
 *
 * At byte 0, sixteen-bit indices: two indices nothing should read (the
 * bind starts at byte 4), two more the first index skips, then the two
 * quads 0 and 1 of a draw with vertex offset 4.  At byte 256, thirty-two-bit
 * indices: one quad, for draws that pick the quad with their vertex offset.
 */
static void
i915_vkx_indices_write(
	struct i915_vkx *x)
{
	static const uint16_t short_indices[16] = {
		0xffffU, 0xffffU,
		0xfff0U, 0xfff0U,
		0U, 1U, 2U, 0U, 2U, 3U,
		4U, 5U, 6U, 4U, 6U, 7U,
	};
	static const uint32_t long_indices[6] = {
		0U, 1U, 2U, 0U, 2U, 3U,
	};
	uint8_t *indices;

	/* Writes both kinds and flushes them before the GPU reads them. */
	indices = x->cpu + I915_VKX_INDEX_OFFSET;
	kern_memcpy(indices, short_indices, sizeof(short_indices));
	kern_memcpy(indices + I915_VKX_INDEX32_OFFSET, long_indices, sizeof(long_indices));
	drv_i915_gt_clflush(indices, I915_VKX_INDEX_BYTES);
}

/* Appends one little-endian word to the stream; a stream that would overflow is marked. */
static void
i915_vkx_put32(
	struct i915_vkx *x,
	uint32_t value)
{
	/* Refuses a word past the end of the stream. */
	if (x->used + 4U > sizeof(x->wire)) {
		x->overflow = 1;
		return;
	}

	kern_memcpy(x->wire + x->used, &value, 4U);
	x->used += 4U;
}

/* Appends one little-endian double word to the stream. */
static void
i915_vkx_put64(
	struct i915_vkx *x,
	uint64_t value)
{
	/* The low word first. */
	i915_vkx_put32(x, (uint32_t)value);
	i915_vkx_put32(x, (uint32_t)(value >> 32));
}

/* Appends the head of a recording: [opcode][no reply][command buffer]. */
static void
i915_vkx_record(
	struct i915_vkx *x,
	uint32_t opcode)
{
	/* A recording asks for no reply. */
	i915_vkx_put32(x, opcode);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, I915_VKX_ID_COMMAND_BUFFER);
}

/* Executes the stream built so far and empties it; the replies stay in the reply area. */
static int
i915_vkx_execute(
	struct i915_vkx *x,
	const char *what)
{
	int error;

	/* Refuses a stream that did not fit. */
	if (x->overflow != 0) {
		kern_logf("i915: vkx: %s: the stream does not fit %u bytes\n", what, I915_VKX_WIRE_BYTES);
		return ENOSPC;
	}

	/* Executes it into the reply area. */
	x->reply_bytes = sizeof(x->reply);
	error = drv_i915_render_execute(x->render, x->wire, x->used, x->reply, &x->reply_bytes);
	x->used = 0U;
	if (error != 0) {
		kern_logf("i915: vkx: %s: the executor refused the stream: %d\n", what, error);
		return error;
	}

	/* Succeeded: the replies are in the reply area. */
	return 0;
}

/* Reads one reply word; zero past the replies. */
static uint32_t
i915_vkx_reply32(
	const struct i915_vkx *x,
	size_t offset)
{
	uint32_t value;

	/* A word past the replies reads as zero. */
	if (offset + 4U > x->reply_bytes)
		return 0U;

	kern_memcpy(&value, x->reply + offset, 4U);

	/* Succeeded: the word at the offset. */
	return value;
}

/* Creates the command pool and allocates its one primary command buffer. */
static int
i915_vkx_pool_create(
	struct i915_vkx *x)
{
	uint32_t result;
	int error;

	/* vkCreateCommandPool: [85][reply][device][present][sType 39][no chain][flags][family][no allocator][present][identity]. */
	x->used = 0U;
	i915_vkx_put32(x, I915_VKX_OP_CREATE_COMMAND_POOL);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put32(x, 39U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put64(x, I915_VKX_ID_POOL);

	/* vkAllocateCommandBuffers: [88][reply][device][present][sType 40][no chain][pool][primary][1][1][identity]. */
	i915_vkx_put32(x, I915_VKX_OP_ALLOCATE_COMMAND_BUFFERS);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put32(x, 40U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, I915_VKX_ID_POOL);
	i915_vkx_put32(x, VK_COMMAND_BUFFER_LEVEL_PRIMARY);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put64(x, I915_VKX_ID_COMMAND_BUFFER);
	error = i915_vkx_execute(x, "create the command pool");
	if (error != 0)
		return error;

	/* The pool exists from here on, whatever the allocation answered. */
	x->pooled = 1;

	/* Refuses a pool the executor did not make: [85][result][present][identity]. */
	result = i915_vkx_reply32(x, 4U);
	if (result != VK_SUCCESS)
		return EIO;

	/* Refuses a buffer it did not allocate: [88][result][count][identity] behind the pool's reply. */
	result = i915_vkx_reply32(x, 24U + 4U);
	if (result != VK_SUCCESS)
		return EIO;

	/* Succeeded: the command buffer can record. */
	return 0;
}

/* Appends vkBeginCommandBuffer, which empties the recording: [90][reply][buffer][present][sType 42][no chain][flags][no inheritance]. */
static void
i915_vkx_begin(
	struct i915_vkx *x)
{
	/* The begin asks for its reply. */
	x->used = 0U;
	x->overflow = 0;
	i915_vkx_put32(x, I915_VKX_OP_BEGIN_COMMAND_BUFFER);
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, I915_VKX_ID_COMMAND_BUFFER);
	i915_vkx_put64(x, 1U);
	i915_vkx_put32(x, 42U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, 0U);
}

/*
 * Appends vkCmdBeginRenderPass of the whole target, cleared to opaque black:
 * [present][sType 43][no chain][pass][framebuffer][area][present][1]
 * {[colour][tag][4][r g b a]}[inline].
 */
static void
i915_vkx_begin_pass(
	struct i915_vkx *x)
{
	/* The begin info. */
	i915_vkx_record(x, I915_VKX_OP_BEGIN_RENDER_PASS);
	i915_vkx_put64(x, 1U);
	i915_vkx_put32(x, 43U);
	i915_vkx_put64(x, 0U);
	i915_vkx_put64(x, I915_VKX_ID_PASS);
	i915_vkx_put64(x, I915_VKX_ID_FRAMEBUFFER);

	/* The render area: the whole target. */
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, I915_VKX_SIZE);
	i915_vkx_put32(x, I915_VKX_SIZE);

	/* One colour clear value: opaque black. */
	i915_vkx_put32(x, 1U);
	i915_vkx_put64(x, 1U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put32(x, 0U);
	i915_vkx_put64(x, 4U);
	i915_vkx_put32(x, I915_VKX_F_0);
	i915_vkx_put32(x, I915_VKX_F_0);
	i915_vkx_put32(x, I915_VKX_F_0);
	i915_vkx_put32(x, I915_VKX_F_1);

	/* The subpass contents are inline. */
	i915_vkx_put32(x, VK_SUBPASS_CONTENTS_INLINE);
}

